"""Reference values for QuantileRegressor's L1 penalty (#311) from
scikit-learn's QuantileRegressor (HiGHS LP).

Run: python validation/python/generate_quantile_l1_validation.py > tests/fixtures/quantile_l1_validation.rs
"""
import numpy as np
import sklearn
from sklearn.linear_model import QuantileRegressor

def arr(v):
    return ", ".join(repr(float(t)) for t in np.ravel(v))

rng = np.random.RandomState(311)
n, p = 50, 4
X = np.round(rng.normal(size=(n, p)), 3)
y = np.round(0.5 + 2.0 * X[:, 0] - 1.0 * X[:, 1] + 0.3 * X[:, 2] + rng.standard_t(3, size=n), 3)
w = np.round(rng.uniform(0.2, 2.0, size=n), 2)

print("// Generated by validation/python/generate_quantile_l1_validation.py")
print(f"// scikit-learn {sklearn.__version__}, numpy {np.__version__}")
print(f"const X: [f64; {X.size}] = [{arr(X)}];")
print(f"const Y: [f64; {y.size}] = [{arr(y)}];")
print(f"const W: [f64; {w.size}] = [{arr(w)}];")
print("/// (quantile, alpha, fit_intercept, weighted, coef, intercept, objective)")
print("#[allow(clippy::type_complexity)]")
print("const CASES: &[(f64, f64, bool, bool, &[f64], f64, f64)] = &[")
for q in [0.5, 0.25, 0.9]:
    for alpha in [0.0, 0.01, 0.05, 0.2, 1.0]:
        for fi in [True, False]:
            for weighted in [False, True]:
                sw = w if weighted else np.ones(n)
                m = QuantileRegressor(quantile=q, alpha=alpha, fit_intercept=fi, solver="highs").fit(X, y, sample_weight=sw)
                r = y - X @ m.coef_ - m.intercept_
                rho = np.where(r >= 0, q * r, (q - 1) * r)
                obj = np.sum(sw * rho) / np.sum(sw) + alpha * np.abs(m.coef_).sum()
                print(f"    ({q}, {alpha}, {str(fi).lower()}, {str(weighted).lower()}, &[{arr(m.coef_)}], {float(m.intercept_)!r}, {float(obj)!r}),")
print("];")

"""Reference values for HuberRegressor's joint (coefficients, scale) estimator
(#310) from scikit-learn's HuberRegressor (L-BFGS-B, fully converged).

Run: python validation/python/generate_huber_joint_validation.py > tests/fixtures/huber_joint_validation.rs
"""
import numpy as np
import sklearn
from sklearn.datasets import load_diabetes
from sklearn.linear_model import HuberRegressor

def arr(v):
    return ", ".join(repr(float(t)) for t in np.ravel(v))

X, y = load_diabetes(return_X_y=True)
X = X[:120]
y = y[:120]
rng = np.random.RandomState(310)
xs = np.round(rng.normal(size=(60, 2)), 3)
ys = np.round(1.0 + 2.0 * xs[:, 0] - xs[:, 1] + rng.standard_t(2, size=60), 3)
ys[[3, 17, 41]] += [12.0, -9.0, 15.0]

print("// Generated by validation/python/generate_huber_joint_validation.py")
print(f"// scikit-learn {sklearn.__version__}, numpy {np.__version__}")
print(f"const X_DIAB: [f64; {X.size}] = [{arr(X)}];")
print(f"const Y_DIAB: [f64; {y.size}] = [{arr(y)}];")
print(f"const X_SYN: [f64; {xs.size}] = [{arr(xs)}];")
print(f"const Y_SYN: [f64; {ys.size}] = [{arr(ys)}];")
print("/// (data: 0 diabetes / 1 synthetic, epsilon, alpha, fit_intercept, coef, intercept, scale, n_outliers, objective)")
print("#[allow(clippy::type_complexity)]")
print("const CASES: &[(u8, f64, f64, bool, &[f64], f64, f64, usize, f64)] = &[")
from sklearn.linear_model._huber import _huber_loss_and_gradient
for data, (Xd, yd) in [(0, (X, y)), (1, (xs, ys))]:
    for eps, alpha, fi in [(1.35, 1e-4, True), (1.35, 1.0, True), (1.8, 1e-4, True), (1.35, 1e-4, False), (1.1, 0.0, True)]:
        m = HuberRegressor(epsilon=eps, alpha=alpha, fit_intercept=fi, max_iter=100000, tol=1e-12).fit(Xd, yd)
        w = np.r_[m.coef_, [m.intercept_] if fi else [], m.scale_]
        obj = _huber_loss_and_gradient(w, Xd, yd, eps, alpha, np.ones(len(yd)))[0]
        print(f"    ({data}, {eps}, {alpha}, {str(fi).lower()}, &[{arr(m.coef_)}], {float(m.intercept_)!r}, {float(m.scale_)!r}, {int(m.outliers_.sum())}, {float(obj)!r}),")
print("];")

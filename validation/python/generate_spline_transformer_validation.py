"""Reference values for `splines::BSpline` (#309) from scikit-learn's
SplineTransformer.

Run: python validation/python/generate_spline_transformer_validation.py > tests/fixtures/spline_transformer_validation.rs
"""
import numpy as np
import sklearn
from sklearn.preprocessing import SplineTransformer

rng = np.random.RandomState(309)
x_train = np.round(rng.gamma(2.0, 1.5, size=40), 3)
x_query = np.r_[np.round(np.linspace(-2.0, 14.0, 23), 3), x_train.min(), x_train.max()]

def arr(v):
    return ", ".join(repr(float(t)) for t in np.ravel(v))

print("// Generated by validation/python/generate_spline_transformer_validation.py")
print(f"// scikit-learn {sklearn.__version__}, numpy {np.__version__}")
print(f"const X_TRAIN: [f64; {x_train.size}] = [{arr(x_train)}];")
print(f"const X_QUERY: [f64; {x_query.size}] = [{arr(x_query)}];")
print("/// (n_knots, degree, knots (0 uniform, 1 quantile, 2 explicit), extrapolation, include_bias, n_columns, row-major basis at X_QUERY)")
print("#[allow(clippy::type_complexity)]")
print("const CASES: &[(usize, usize, u8, &str, bool, usize, &[f64])] = &[")
explicit = np.array([[0.0], [1.0], [2.5], [6.0], [9.0]])
for extrap in ["constant", "linear", "continue", "periodic", "error"]:
    for knots in ["uniform", "quantile", "explicit"]:
        for n_knots, degree in [(5, 3), (4, 2), (6, 1), (3, 0), (7, 3)]:
            if extrap == "periodic" and degree >= n_knots:
                continue
            for bias in [True, False]:
                k = explicit if knots == "explicit" else knots
                st = SplineTransformer(n_knots=n_knots, degree=degree, knots=k,
                                       extrapolation=extrap, include_bias=bias)
                st.fit(x_train[:, None])
                if extrap == "error":
                    lo, hi = st.bsplines_[0].t[degree], st.bsplines_[0].t[-degree - 1]
                    q = x_query[(x_query >= lo) & (x_query <= hi)]
                    q = np.r_[q, np.full(x_query.size - q.size, lo)]
                else:
                    q = x_query
                try:
                    b = st.transform(q[:, None])
                except ValueError:
                    continue
                code = {"uniform": 0, "quantile": 1, "explicit": 2}[knots]
                print(f'    ({n_knots if knots != "explicit" else 5}, {degree}, {code}, "{extrap}", {str(bias).lower()}, {b.shape[1]}, &[{arr(b)}]),')
print("];")
print(f"const EXPLICIT_KNOTS: [f64; 5] = [{arr(explicit)}];")

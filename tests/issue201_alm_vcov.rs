const N: usize = 80;

/// Distribution, response, extra parameter, coefficients, SEs and name.
type AlmCase<'a> = (
    AlmDistribution,
    &'a [f64; N],
    Option<f64>,
    [f64; 2],
    [f64; 2],
    &'a str,
);

#[test]
fn alm_standard_errors_match_greybox() {
    use AlmDistribution as D;
    let x = Mat::from_fn(N, 1, |i, _| X[i]);
    let cases: [AlmCase; 12] = [
        (D::Normal, &YN, None, NORMAL_COEF, NORMAL_SE, "normal"),
        (
            D::LogNormal,
            &YPOS,
            None,
            LOGNORMAL_COEF,
            LOGNORMAL_SE,
            "lognormal",
        ),
        (D::Poisson, &YP, None, POISSON_COEF, POISSON_SE, "poisson"),
        (D::Gamma, &YPOS, None, GAMMA_COEF, GAMMA_SE, "gamma"),
        (
            D::InverseGaussian,
            &YPOS,
            None,
            INVGAUSS_COEF,
            INVGAUSS_SE,
            "inverse gaussian",
        ),
        (
            D::Exponential,
            &YPOS,
            None,
            EXPONENTIAL_COEF,
            EXPONENTIAL_SE,
            "exponential",
        ),
        (
            D::Logistic,
            &YN,
            None,
            LOGISTIC_COEF,
            LOGISTIC_SE,
            "logistic",
        ),
        (
            D::GeneralisedNormal,
            &YN,
            Some(2.0),
            GNORM_COEF,
            GNORM_SE,
            "generalised normal",
        ),
        (
            D::Geometric,
            &YP,
            None,
            GEOMETRIC_COEF,
            GEOMETRIC_SE,
            "geometric",
        ),
        (
            D::NegativeBinomial,
            &YP,
            Some(1.0),
            NBINOM_COEF,
            NBINOM_SE,
            "negative binomial",
        ),
        (
            D::Binomial,
            &YB,
            None,
            BINOMIAL_COEF,
            BINOMIAL_SE,
            "binomial",
        ),
        (
            D::FoldedNormal,
            &YPOS,
            None,
            FNORM_COEF,
            FNORM_SE,
            "folded normal",
        ),
    ];
    for (dist, y, extra, coef, se, what) in cases {
        let y = Col::from_fn(N, |i| y[i]);
        let mut b = AlmRegressor::builder()
            .distribution(dist)
            .compute_inference(true);
        if let Some(e) = extra {
            b = b.extra_parameter(e);
        }
        let fit = b.build().fit(&x, &y).unwrap();
        let r = fit.result();
        let mut got_coef = [r.intercept.unwrap(), r.coefficients[0]];
        if dist == D::Binomial {
            // greybox's `dbinom` regression models P(y = 0): coefficients flip sign
            got_coef = [-got_coef[0], -got_coef[1]];
        }
        let got_se = [
            r.intercept_std_error.unwrap(),
            r.std_errors.as_ref().unwrap()[0],
        ];
        for k in 0..2 {
            assert!(
                (got_coef[k] - coef[k]).abs() < 1e-5 * (1.0 + coef[k].abs()),
                "{what} coef {k}: {} vs greybox {}",
                got_coef[k],
                coef[k]
            );
            assert!(
                (got_se[k] - se[k]).abs() < 1e-4 * se[k],
                "{what} se {k}: {} vs greybox {}",
                got_se[k],
                se[k]
            );
        }
    }
}

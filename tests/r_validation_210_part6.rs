fn col(v: &[f64]) -> Col<f64> {
    Col::from_fn(v.len(), |i| v[i])
}

fn assert_close(got: &[f64], want: &[f64], tol: f64, what: &str) {
    assert_eq!(got.len(), want.len(), "{what}: length");
    for (k, (g, w)) in got.iter().zip(want).enumerate() {
        assert!(
            (g - w).abs() <= tol * (1.0 + w.abs()),
            "{what}[{k}]: {g} vs R {w}"
        );
    }
}

fn v(c: &Col<f64>) -> Vec<f64> {
    c.iter().copied().collect()
}

#[test]
fn huber_weights_and_wald_table_match_rlm() {
    let f = HuberRegressor::builder()
        .epsilon(1.345)
        .alpha(0.0)
        .tolerance(1e-14)
        .max_iterations(500)
        .compute_inference(true)
        .build()
        .fit(&x(), &col(&Y_HUBER))
        .unwrap();
    let r = f.result();
    let (lo0, hi0) = r.intercept_conf_interval.unwrap();
    let with0 = |a: f64, b: &Option<Col<f64>>| [vec![a], v(b.as_ref().unwrap())].concat();
    let got = [
        with0(r.intercept.unwrap(), &Some(r.coefficients.clone())),
        with0(r.intercept_std_error.unwrap(), &r.std_errors),
        with0(r.intercept_t_statistic.unwrap(), &r.t_statistics),
        with0(r.intercept_p_value.unwrap(), &r.p_values),
        with0(lo0, &r.conf_interval_lower),
        with0(hi0, &r.conf_interval_upper),
        vec![f.scale()],
    ]
    .concat();
    assert_close(&got, &HUBER_TABLE, 1e-8, "huber table");
    assert_close(&v(&f.weights()), &HUBER_W, 1e-8, "huber weights");
}


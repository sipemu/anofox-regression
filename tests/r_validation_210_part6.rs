fn aft(dist: AftDistribution, intercept: bool) -> anofox_regression::solvers::aft::FittedAft {
    let event: Vec<bool> = EVENT.iter().map(|&e| e == 1.0).collect();
    AftRegressor::builder()
        .distribution(dist)
        .with_intercept(intercept)
        .compute_inference(true)
        .tolerance(1e-15)
        .max_iterations(500)
        .build()
        .fit(&x(), &col(&TIME), &event)
        .unwrap()
}

#[test]
fn aft_without_intercept_matches_survreg() {
    let f = aft(AftDistribution::Weibull, false);
    assert!(f.intercept().is_none());
    let se = &f.inference().unwrap().std_errors;
    let got = [
        f.coefficients()[0],
        f.coefficients()[1],
        se[0],
        se[1],
        f.scale(),
        f.log_likelihood(),
        f.aic(),
    ];
    assert_close(&got, &AFT_NOINT, 1e-7, "weibull without intercept");
}

#[test]
fn aft_predictions_match_predict_survreg() {
    for (dist, want) in [
        (AftDistribution::Weibull, &AFT_WEIBULL_PRED),
        (AftDistribution::LogNormal, &AFT_LOGNORMAL_PRED),
    ] {
        let f = aft(dist, true);
        let got = [
            v(&f.predict_linear(&new_x())),
            v(&f.predict_quantile(&new_x(), 0.3)),
            v(&f.predict_cdf(&new_x(), 2.0)),
        ]
        .concat();
        assert_close(&got, want, 1e-7, &format!("{dist:?}"));
        let s = f.predict_survival(&new_x(), 2.0);
        let cdf = f.predict_cdf(&new_x(), 2.0);
        for i in 0..3 {
            assert!((s[i] + cdf[i] - 1.0).abs() < 1e-12);
        }
    }
}


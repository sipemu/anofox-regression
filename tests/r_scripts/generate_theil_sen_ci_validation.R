#!/usr/bin/env Rscript
# Reference values for the exact (Sen 1968) Theil-Sen slope interval and
# Kendall's test (#92). Writes tests/fixtures/theil_sen_ci_validation.rs.
#
#   Rscript tests/r_scripts/generate_theil_sen_ci_validation.R \
#       > tests/fixtures/theil_sen_ci_validation.rs
#
# Oracles:
#  - trend::sens.slope (x = 1..n): interval, continuity-corrected z, p-value.
#  - General x with ties in x and y: the same rank rule on the pairwise slopes
#    with Kendall's tie-corrected Var(S) as in stats::cor.test(method =
#    "kendall"); z and p from cor.test(..., continuity = TRUE).
suppressPackageStartupMessages(library(trend))

f <- function(v) formatC(v, digits = 17, format = "e")
arr <- function(name, v) cat(sprintf("const %s: [f64; %d] = [%s];\n", name, length(v), paste(f(v), collapse = ", ")))
num <- function(name, v) cat(sprintf("const %s: f64 = %s;\n", name, if (is.na(v)) "f64::NAN" else f(v)))

cat("// Generated by tests/r_scripts/generate_theil_sen_ci_validation.R\n")
cat(sprintf("// %s, trend %s\n\n", R.version.string, packageVersion("trend")))

# Case 1: a series against time, with ties in y.
set.seed(222)
n <- 30
y1 <- round(0.4 * (1:n) + rnorm(n, sd = 2), 1)
arr("Y_SENS", y1)
for (lev in c(0.95, 0.9)) {
  s <- sens.slope(y1, conf.level = lev)
  tag <- sprintf("%02d", round(100 * lev))
  num(paste0("SENS_LO_", tag), s$conf.int[1])
  num(paste0("SENS_HI_", tag), s$conf.int[2])
  num(paste0("SENS_SLOPE_", tag), s$estimates)
  num(paste0("SENS_Z_", tag), s$statistic)
  num(paste0("SENS_P_", tag), s$p.value)
}

# Case 2: general x with ties in x and in y.
sen_ci <- function(x, y, lev) {
  n <- length(x)
  d <- c()
  for (i in 1:(n - 1)) for (j in (i + 1):n) if (x[i] != x[j]) d <- c(d, (y[j] - y[i]) / (x[j] - x[i]))
  ties <- function(v) { t <- table(v); as.numeric(t[t > 1]) }
  tx <- ties(x); ty <- ties(y)
  v0 <- n * (n - 1) * (2 * n + 5)
  vt <- sum(tx * (tx - 1) * (2 * tx + 5)); vu <- sum(ty * (ty - 1) * (2 * ty + 5))
  v1 <- sum(tx * (tx - 1)) * sum(ty * (ty - 1))
  v2 <- sum(tx * (tx - 1) * (tx - 2)) * sum(ty * (ty - 1) * (ty - 2))
  varS <- (v0 - vt - vu) / 18 + v1 / (2 * n * (n - 1)) + v2 / (9 * n * (n - 1) * (n - 2))
  k <- length(d)
  C <- qnorm(1 - (1 - lev) / 2) * sqrt(varS)
  sd <- sort(d)
  ct <- suppressWarnings(cor.test(x, y, method = "kendall", exact = FALSE, continuity = TRUE))
  c(lo = sd[round((k - C) / 2)], hi = sd[round((k + C) / 2 + 1)], slope = median(d),
    z = unname(ct$statistic), p = ct$p.value)
}
set.seed(7)
x2 <- sample(1:12, 25, replace = TRUE)
y2 <- round(3 - 0.8 * x2 + rt(25, df = 3), 0)
arr("X_TIES", x2)
arr("Y_TIES", y2)
r <- sen_ci(x2, y2, 0.95)
num("TIES_LO", r["lo"]); num("TIES_HI", r["hi"]); num("TIES_SLOPE", r["slope"])
num("TIES_Z", r["z"]); num("TIES_P", r["p"])

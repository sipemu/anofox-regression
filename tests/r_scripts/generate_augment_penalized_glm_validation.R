#!/usr/bin/env Rscript
# Reference values for diagnostics::augment_glm on the penalized GLM engine
# (fitted, residuals, rstandard, rstudent, hatvalues, cooks.distance, dffits).
# Run from the crate root:
#   Rscript tests/r_scripts/generate_augment_penalized_glm_validation.R \
#     > tests/fixtures/augment_penalized_glm_validation.rs
suppressPackageStartupMessages({ library(MASS) })
have_statmod <- requireNamespace("statmod", quietly = TRUE)
ctl <- glm.control(epsilon = 1e-14, maxit = 200)

fmt <- function(v) paste(sprintf("%.17e", v), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(v)))
num <- function(name, v) cat(sprintf("pub const %s: f64 = %s;\n", name, sprintf("%.17e", v)))

cat("// Generated by tests/r_scripts/generate_augment_penalized_glm_validation.R -- do not edit.\n")
cat(sprintf("// %s, MASS %s, statmod %s\n", R.version.string, packageVersion("MASS"),
            if (have_statmod) as.character(packageVersion("statmod")) else "n/a"))
cat("#![allow(dead_code)]\n\n")
cat("pub struct AugRef {\n")
for (f in c("fitted", "dev", "pear", "resp", "rstd_dev", "rstd_pear", "rstud", "hat", "cook", "dffits"))
  cat(sprintf("    pub %s: &'static [f64],\n", f))
cat("}\n\n")
cat(sprintf("pub const HAVE_TWEEDIE: bool = %s;\n", if (have_statmod) "true" else "false"))

# 30 rows, 2 features; row 30 has an extreme x1 (high leverage).
set.seed(20261011)
n <- 30
x1 <- round(c(seq(0.1, 2.9, length.out = n - 1) + runif(n - 1, -0.2, 0.2), 6.0), 3)
x2 <- round(1.5 * cos(seq_len(n)) + runif(n, -0.3, 0.3), 3)
arr("X1", x1); arr("X2", x2)

mu_cnt <- exp(0.3 + 0.4 * x1 - 0.3 * x2)
y_pois <- rpois(n, mu_cnt)
y_bin <- rbinom(n, 1, plogis(-0.5 + 0.8 * x1 - 0.6 * x2)); y_bin[n] <- 0
y_prop <- round(pmin(pmax(plogis(-0.5 + 0.5 * x1 - 0.4 * x2) + runif(n, -0.15, 0.15), 0.02), 0.98), 3)
y_nb <- rnbinom(n, size = 1.5, mu = exp(0.5 + 0.4 * x1 - 0.3 * x2))
mu_pos <- exp(0.2 + 0.3 * x1 - 0.2 * x2)
y_gamma <- round(rgamma(n, shape = 3, scale = mu_pos / 3), 4)
expo <- round(runif(n, 0.5, 3), 3)
log_expo <- log(expo)
y_off <- rpois(n, expo * mu_cnt)
arr("Y_POIS", y_pois); arr("Y_BIN", y_bin); arr("Y_PROP", y_prop); arr("Y_NB", y_nb)
arr("Y_GAMMA", y_gamma); arr("LOG_EXPO", log_expo); arr("Y_OFF", y_off)

# unit_disp: R's glm.nb (summary.negbin) uses dispersion 1 for rstandard /
# cooks.distance; for a glm(family = negative.binomial(theta)) object we apply
# that convention explicitly so the reference matches a glm.nb fit at fixed theta.
aug <- function(prefix, m, unit_disp = FALSE) {
  infl <- influence(m, do.coef = FALSE)
  h <- infl$hat
  arr(paste0(prefix, "_FITTED"), fitted(m))
  arr(paste0(prefix, "_RESID_DEV"), residuals(m, type = "deviance"))
  arr(paste0(prefix, "_RESID_PEAR"), residuals(m, type = "pearson"))
  arr(paste0(prefix, "_RESID_RESP"), residuals(m, type = "response"))
  if (unit_disp) {
    arr(paste0(prefix, "_RSTD_DEV"), infl$dev.res / sqrt(1 - h))
    arr(paste0(prefix, "_RSTD_PEAR"), infl$pear.res / sqrt(1 - h))
    arr(paste0(prefix, "_COOK"), cooks.distance(m, dispersion = 1))
  } else {
    arr(paste0(prefix, "_RSTD_DEV"), rstandard(m, type = "deviance"))
    arr(paste0(prefix, "_RSTD_PEAR"), rstandard(m, type = "pearson"))
    arr(paste0(prefix, "_COOK"), cooks.distance(m))
  }
  arr(paste0(prefix, "_RSTUD"), rstudent(m))
  arr(paste0(prefix, "_HAT"), hatvalues(m))
  arr(paste0(prefix, "_DFFITS"), dffits(m))
  sfx <- c(fitted = "FITTED", dev = "RESID_DEV", pear = "RESID_PEAR", resp = "RESID_RESP",
           rstd_dev = "RSTD_DEV", rstd_pear = "RSTD_PEAR", rstud = "RSTUD", hat = "HAT",
           cook = "COOK", dffits = "DFFITS")
  cat(sprintf("pub const %s: AugRef = AugRef { %s };\n", prefix,
              paste(sprintf("%s: &%s_%s", names(sfx), prefix, sfx), collapse = ", ")))
}

cat("\n// Poisson (log)\n")
aug("POIS", glm(y_pois ~ x1 + x2, family = poisson, control = ctl))
cat("\n// Poisson (log) with offset log(exposure)\n")
aug("POFF", glm(y_off ~ x1 + x2 + offset(log_expo), family = poisson, control = ctl))
cat("\n// quasipoisson (Pearson dispersion)\n")
aug("QPOIS", glm(y_pois ~ x1 + x2, family = quasipoisson, control = ctl))
cat("\n// Binomial (logit), 0/1 response (also the logistic reference)\n")
aug("BIN", glm(y_bin ~ x1 + x2, family = binomial, control = ctl))
cat("\n// Binomial (logit), proportions without weights\n")
aug("PROP", suppressWarnings(glm(y_prop ~ x1 + x2, family = binomial, control = ctl)))
cat("\n// Negative binomial, theta estimated (MASS::glm.nb)\n")
nb <- glm.nb(y_nb ~ x1 + x2, control = ctl)
num("NB_THETA", nb$theta)
aug("NB", nb)
cat("\n// Negative binomial, theta fixed at 2\n")
aug("NBF", glm(y_nb ~ x1 + x2, family = negative.binomial(2), control = ctl), unit_disp = TRUE)
cat("\n// Gamma (log)\n")
aug("GAMMA", glm(y_gamma ~ x1 + x2, family = Gamma(link = "log"), control = ctl))
if (have_statmod) {
  # Compound Poisson-gamma draws with p = 1.5, phi = 1: N ~ Pois(mu^0.5 / 0.5),
  # each jump Gamma(shape 1, scale 0.5 mu^0.5).
  set.seed(7)
  cnt <- rpois(n, mu_pos^0.5 / 0.5)
  y_tw <- round(vapply(seq_len(n), function(i)
    sum(rgamma(cnt[i], shape = 1, scale = 0.5 * mu_pos[i]^0.5)), numeric(1)), 4)
  arr("Y_TW", y_tw)
  cat("\n// Tweedie (p = 1.5, log link), statmod::tweedie\n")
  aug("TW", glm(y_tw ~ x1 + x2, family = statmod::tweedie(var.power = 1.5, link.power = 0),
                control = ctl))
} else {
  # No statmod: empty placeholders; the Rust test then skips the R comparison.
  cat("pub const Y_TW: [f64; 0] = [];\n")
  cat("pub const TW: AugRef = AugRef { fitted: &[], dev: &[], pear: &[], resp: &[], rstd_dev: &[], rstd_pear: &[], rstud: &[], hat: &[], cook: &[], dffits: &[] };\n")
}

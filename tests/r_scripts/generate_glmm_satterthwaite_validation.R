#!/usr/bin/env Rscript
# =============================================================================
# GLMM inference references (issue #89 / DataZooDE/anofox-statistics#218):
#
#   * Satterthwaite t-tests of the fixed effects of a Gaussian LMM:
#     lmerTest::contest1D(as_lmerModLmerTest(m), e_j, confint = TRUE) for every
#     unit contrast e_j -> df, p-value and 95% t interval;
#   * the fixed-effect covariance vcov(m);
#   * conditional standard errors of the BLUPs:
#     sqrt(diag(attr(ranef(m, condVar = TRUE)[[f]], "postVar")));
#   * BLUP intervals: broom.mixed::tidy(m, effects = "ran_vals", conf.int = TRUE);
#   * fitted(m), predict(m, re.form = NA, type = "response") and
#     residuals(m, type = "pearson"); df.residual(m).
#
# Reads the scenario data from tests/fixtures/glmm_validation.rs and
# tests/fixtures/glmm_families_validation.rs (byte-identical inputs to the
# Rust tests). Needs lme4, lmerTest and broom.mixed.
#
#   Rscript tests/r_scripts/generate_glmm_satterthwaite_validation.R \
#       > tests/fixtures/glmm_inference_validation.rs
# =============================================================================
suppressPackageStartupMessages({
  library(lme4)
  library(lmerTest)
  library(broom.mixed)
})

src <- c(readLines("tests/fixtures/glmm_validation.rs"),
         readLines("tests/fixtures/glmm_families_validation.rs"))
arr <- function(name) {
  line <- grep(paste0("^const ", name, ":"), src, value = TRUE)
  stopifnot(length(line) == 1)
  as.numeric(strsplit(sub(".*= \\[(.*)\\];", "\\1", line), ",\\s*")[[1]])
}
vec <- function(name, v) {
  cat(sprintf("const %s: [f64; %d] = [%s];\n", name, length(v),
              paste(sprintf("%.15e", v), collapse = ", ")))
}

emit <- function(tag, m, satterthwaite = FALSE, observations = FALSE) {
  cat(sprintf("\n// %s\n", tag))
  V <- as.matrix(vcov(m))
  vec(paste0(tag, "_VCOV"), as.vector(t(V)))
  if (satterthwaite) {
    mt <- as_lmerModLmerTest(m)
    p <- length(fixef(m))
    rows <- lapply(seq_len(p), function(j) {
      L <- numeric(p); L[j] <- 1
      contest1D(mt, L, confint = TRUE, level = 0.95)
    })
    vec(paste0(tag, "_SATT_DF"), sapply(rows, function(r) r$df))
    vec(paste0(tag, "_SATT_P"), sapply(rows, function(r) r[["Pr(>|t|)"]]))
    vec(paste0(tag, "_SATT_LO95"), sapply(rows, function(r) r$lower))
    vec(paste0(tag, "_SATT_HI95"), sapply(rows, function(r) r$upper))
  }
  re <- ranef(m, condVar = TRUE)
  for (f in names(re)) {
    pv <- attr(re[[f]], "postVar")
    # J x q, row-major per level, levels in R's (sorted) factor order.
    se <- t(apply(pv, 3, function(s) sqrt(diag(as.matrix(s)))))
    if (dim(pv)[1] == 1) se <- t(se)
    vec(paste0(tag, "_RE_SE_", toupper(gsub("[^A-Za-z]", "", f))), as.vector(t(se)))
  }
  # broom.mixed ran_vals intervals, rows ordered as the RE_SE arrays (level, term).
  rv <- as.data.frame(broom.mixed::tidy(m, effects = "ran_vals", conf.int = TRUE, conf.level = 0.95))
  for (f in unique(rv$group)) {
    r <- rv[rv$group == f, ]
    terms <- unique(r$term)
    r <- r[order(as.numeric(as.character(r$level)), match(r$term, terms)), ]
    key <- toupper(gsub("[^A-Za-z]", "", f))
    vec(paste0(tag, "_RANVALS_LO95_", key), r$conf.low)
    vec(paste0(tag, "_RANVALS_HI95_", key), r$conf.high)
  }
  if (observations) {
    vec(paste0(tag, "_FITTED"), unname(fitted(m)))
    vec(paste0(tag, "_FITTED_POP"), unname(predict(m, re.form = NA, type = "response")))
    vec(paste0(tag, "_PEARSON"), unname(residuals(m, type = "pearson")))
    cat(sprintf("const %s_DF_RESID: f64 = %.15e;\n", tag, df.residual(m)))
  }
}

cat("// =============================================================================\n")
cat("// GLMM inference references — generated by\n")
cat("// tests/r_scripts/generate_glmm_satterthwaite_validation.R\n")
cat(sprintf("// %s ; lme4: %s ; lmerTest: %s ; broom.mixed: %s\n", R.version.string,
            packageVersion("lme4"), packageVersion("lmerTest"), packageVersion("broom.mixed")))
cat("// Data: tests/fixtures/glmm_validation.rs, tests/fixtures/glmm_families_validation.rs\n")
cat("// =============================================================================\n")

# Tight optimizer and PIRLS tolerances: the references should be the optimum,
# not lme4's default stopping point (glmer's default tolPwrss = 1e-7 leaves the
# nAGQ = 0 deviance noisy enough to move theta, and so the SEs, by ~1%).
opt <- list(xtol_abs = 1e-12, ftol_abs = 1e-14, xtol_rel = 1e-12, ftol_rel = 1e-14, maxeval = 1e5)
ctl <- lmerControl(calc.derivs = FALSE, optCtrl = opt)
gctl <- glmerControl(optimizer = "nloptwrap", calc.derivs = FALSE, tolPwrss = 1e-12, optCtrl = opt)
d <- data.frame(x = arr("X_LMM_A"), y = arr("Y_LMM_A"), g = factor(arr("G_LMM_A")))
emit("LMM_A", lmer(y ~ x + (1 | g), d, REML = TRUE, control = ctl), TRUE, TRUE)

d <- data.frame(x1 = arr("X1_LMM_B"), x2 = arr("X2_LMM_B"), y = arr("Y_LMM_B"), g = factor(arr("G_LMM_B")))
emit("LMM_B", lmer(y ~ x1 + x2 + (1 | g), d, REML = TRUE, control = ctl), TRUE)

d <- data.frame(x = arr("X_SLOPE_E"), y = arr("Y_SLOPE_E"), g = factor(arr("G_SLOPE_E")))
emit("SLOPE_E", lmer(y ~ x + (x | g), d, REML = TRUE, control = ctl), TRUE, TRUE)

d <- data.frame(x = arr("X_CROSS_F"), y = arr("Y_CROSS_F"), a = factor(arr("A_CROSS_F")), b = factor(arr("B_CROSS_F")))
emit("CROSS_F", lmer(y ~ x + (1 | a) + (1 | b), d, REML = TRUE, control = ctl), TRUE, TRUE)

d <- data.frame(x = arr("X_ML_H"), y = arr("Y_ML_H"), g = factor(arr("G_ML_H")))
emit("ML_H", lmer(y ~ x + (1 | g), d, REML = FALSE, control = ctl), TRUE)

d <- data.frame(x = arr("X_UNBAL_I"), y = arr("Y_UNBAL_I"), g = factor(arr("G_UNBAL_I")))
emit("UNBAL_I", lmer(y ~ x + (1 | g), d, REML = TRUE, control = ctl), TRUE)

d <- data.frame(x = arr("X_NOINT_K"), y = arr("Y_NOINT_K"), g = factor(arr("G_NOINT_K")))
emit("NOINT_K", lmer(y ~ 0 + x + (1 | g), d, REML = TRUE, control = ctl), TRUE)

d <- data.frame(x = arr("X_POIS_C"), y = arr("Y_POIS_C"), g = factor(arr("G_POIS_C")))
emit("POIS_C", glmer(y ~ x + (1 | g), d, family = poisson, nAGQ = 0, control = gctl), FALSE, TRUE)

d <- data.frame(x = arr("X_BIN_D"), y = arr("Y_BIN_D"), g = factor(arr("G_BIN_D")))
emit("BIN_D", glmer(y ~ x + (1 | g), d, family = binomial, nAGQ = 0, control = gctl), FALSE, TRUE)

d <- data.frame(x = arr("X"), y = arr("Y_NB"), g = factor(arr("G")))
emit("NB_H", glmer.nb(y ~ x + (1 | g), d, nAGQ = 0, control = gctl), FALSE, TRUE)

d <- data.frame(x = arr("X"), y = arr("Y_GA"), g = factor(arr("G")))
emit("GA_J", glmer(y ~ x + (1 | g), d, family = Gamma(link = "log"), nAGQ = 0, control = gctl), FALSE, TRUE)

d <- data.frame(x = arr("X"), y = arr("Y_PO_OFF"), expo = arr("EXPO"), g = factor(arr("G")))
emit("PO_L", glmer(y ~ x + (1 | g) + offset(log(expo)), d, family = poisson, nAGQ = 0, control = gctl), FALSE, TRUE)

d <- data.frame(x = arr("X"), y = arr("Y_M"), o = arr("OFF_M"), g = factor(arr("G")))
emit("LMM_M", lmer(y ~ x + (1 | g) + offset(o), d, REML = TRUE, control = ctl), TRUE, TRUE)

d <- data.frame(x = arr("XC"), y = arr("Y_N"), a = factor(arr("A")), b = factor(arr("B")))
emit("LMM_N", lmer(y ~ x + (x | a) + (1 | b), d, REML = TRUE, control = ctl), TRUE, TRUE)

d <- data.frame(x = arr("XC"), y = arr("Y_O"), a = factor(arr("A")), b = factor(arr("B")))
emit("PO_O", glmer(y ~ x + (x | a) + (1 | b), d, family = poisson, nAGQ = 0, control = gctl), FALSE, TRUE)

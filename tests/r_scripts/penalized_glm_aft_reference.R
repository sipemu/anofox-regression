suppressPackageStartupMessages({ library(MASS); library(survival) })
set.seed(4445)
n <- 60
x1 <- round(rnorm(n), 4); x2 <- round(runif(n, -1, 1), 4)
expo <- round(runif(n, 0.5, 2), 4); off <- log(expo)
yp <- rpois(n, exp(0.3 + 0.5 * x1 - 0.4 * x2) * expo)
yb <- rbinom(n, 1, plogis(-0.2 + 0.9 * x1 + 0.6 * x2))
ynb <- rnbinom(n, mu = exp(1 + 0.4 * x1 - 0.3 * x2), size = 2)
yg <- round(rgamma(n, shape = 3, rate = 3 / exp(0.5 + 0.3 * x1 - 0.2 * x2)), 4)
tt <- round(rweibull(n, shape = 1.5, scale = exp(1 + 0.5 * x1 - 0.3 * x2)), 4)
cens <- round(runif(n, 0.5, 6), 4)
time <- pmin(tt, cens); ev <- as.numeric(tt <= cens)

num <- function(v) { s <- sprintf("%.17g", v); ifelse(grepl("[.eE]", s), s, paste0(s, ".0")) }

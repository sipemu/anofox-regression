# Posterior mode of a Poisson GLM with N(0.5, 0.5^2) on x1 and N(0, 0.25^2) on x2
# (flat intercept), and its Laplace covariance solve(X'WX + P).
X <- cbind(1, x1, x2); P <- diag(c(0, 1 / 0.25, 1 / 0.0625)); m0 <- c(0, 0.5, 0)
nlp <- function(b) { eta <- X %*% b; -sum(yp * eta - exp(eta)) + 0.5 * sum(diag(P) * (b - m0)^2) }
b <- coef(glm(yp ~ x1 + x2, family = poisson, control = ctl))
for (i in 1:50) { mu <- as.vector(exp(X %*% b)); H <- t(X) %*% (X * mu) + P
  g <- t(X) %*% (yp - mu) - P %*% (b - m0); b <- b + as.vector(solve(H, g)) }
mu <- as.vector(exp(X %*% b)); I <- t(X) %*% (X * mu); H <- I + P
cat("// Poisson MAP with priors flat, N(0.5, 0.5), N(0, 0.25): Newton in R\n")
cat("pub const POIS_PRIOR_COEF: [f64; 3] = ", f(b), ";\n", sep = "")
cat("pub const POIS_PRIOR_SE_LAPLACE: [f64; 3] = ", f(sqrt(diag(solve(H)))), ";\n", sep = "")
S <- solve(H) %*% I %*% solve(H)
cat("pub const POIS_PRIOR_SE_SANDWICH: [f64; 3] = ", f(sqrt(diag(S))), ";\n", sep = "")
cat("pub const POIS_PRIOR_SE_NAIVE: [f64; 3] = ", f(sqrt(diag(solve(I)))), ";\n\n", sep = "")


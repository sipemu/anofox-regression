emit_glm("POIS_SQRT", glm(yp ~ x1 + x2, family = poisson(link = "sqrt"), start = c(1, 0, 0), control = ctl))
emit_glm("BIN_LOGIT", glm(yb ~ x1 + x2, family = binomial, control = ctl))

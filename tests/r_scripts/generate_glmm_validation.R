# ------------------------------------------------------------------ Scenario E
# Gaussian LMM with a correlated random intercept + random slope, 10 groups.
{
  suppressMessages(library(MASS))
  J <- 10; ni <- 12; n <- J * ni
  g <- rep(1:J, each = ni)
  x <- round(rnorm(n), 4)
  S <- matrix(c(0.8^2, 0.3 * 0.8 * 0.5, 0.3 * 0.8 * 0.5, 0.5^2), 2, 2)
  bb <- mvrnorm(J, c(0, 0), S)
  y <- round(1.0 + 0.6 * x + bb[g, 1] + bb[g, 2] * x + rnorm(n, 0, 0.5), 4)
  m <- lmer(y ~ x + (x | g), REML = TRUE,
            control = lmerControl(calc.derivs = FALSE))
  vc <- as.data.frame(VarCorr(m))
  # vc rows: 1 = sd(Intercept), 2 = sd(x slope), 3 = corr(Intercept, x).
  cat("// Scenario E: Gaussian LMM with random slope, y ~ x + (x|g), REML\n")
  fmt_vec("X_SLOPE_E", x)
  fmt_vec("G_SLOPE_E", g - 1L, "usize")
  fmt_vec("Y_SLOPE_E", y)
  cat(sprintf("const SLOPE_E_INTERCEPT: f64 = %.10f;\n", fixef(m)[1]))
  cat(sprintf("const SLOPE_E_SLOPE: f64 = %.10f;\n", fixef(m)[2]))
  cat(sprintf("const SLOPE_E_SIGMA: f64 = %.10f;\n", sigma(m)))
  cat(sprintf("const SLOPE_E_SD_INTERCEPT: f64 = %.10f;\n", vc$sdcor[1]))
  cat(sprintf("const SLOPE_E_SD_SLOPE: f64 = %.10f;\n", vc$sdcor[2]))
  cat(sprintf("const SLOPE_E_CORR: f64 = %.10f;\n", vc$sdcor[3]))
  se <- sqrt(diag(vcov(m)))
  cat(sprintf("const SLOPE_E_SE_INTERCEPT: f64 = %.10f;\n", se[1]))
  cat(sprintf("const SLOPE_E_SE_SLOPE: f64 = %.10f;\n", se[2]))
  fmt_vec("SLOPE_E_RANEF_INT", ranef(m)$g[, 1])
  fmt_vec("SLOPE_E_RANEF_SLOPE", ranef(m)$g[, 2])
  cat("\n")
}

# ------------------------------------------------------------------ Scenario F
# Crossed random intercepts: y ~ x + (1|a) + (1|b), a and b fully crossed.
{
  set.seed(11)
  na <- 6; nb <- 5; rp <- 4; n <- na * nb * rp
  a <- rep(1:na, each = nb * rp)
  b <- rep(rep(1:nb, each = rp), times = na)
  x <- round(rnorm(n), 4)
  ba <- rnorm(na, 0, 0.9); bb <- rnorm(nb, 0, 0.6)
  y <- round(1.0 + 0.5 * x + ba[a] + bb[b] + rnorm(n, 0, 0.5), 4)
  m <- lmer(y ~ x + (1 | a) + (1 | b), REML = TRUE,
            control = lmerControl(calc.derivs = FALSE))
  vc <- as.data.frame(VarCorr(m))
  # vc grp order is data-dependent; index by name.
  sd_a <- vc$sdcor[vc$grp == "a"]
  sd_b <- vc$sdcor[vc$grp == "b"]
  cat("// Scenario F: crossed random intercepts, y ~ x + (1|a) + (1|b), REML\n")
  fmt_vec("X_CROSS_F", x)
  fmt_vec("A_CROSS_F", a - 1L, "usize")
  fmt_vec("B_CROSS_F", b - 1L, "usize")
  fmt_vec("Y_CROSS_F", y)
  cat(sprintf("const CROSS_F_INTERCEPT: f64 = %.10f;\n", fixef(m)[1]))
  cat(sprintf("const CROSS_F_SLOPE: f64 = %.10f;\n", fixef(m)[2]))
  cat(sprintf("const CROSS_F_SIGMA: f64 = %.10f;\n", sigma(m)))
  cat(sprintf("const CROSS_F_SD_A: f64 = %.10f;\n", sd_a))
  cat(sprintf("const CROSS_F_SD_B: f64 = %.10f;\n", sd_b))
  cat(sprintf("const CROSS_F_LOGLIK: f64 = %.10f;\n", as.numeric(logLik(m))))
  se <- sqrt(diag(vcov(m)))
  cat(sprintf("const CROSS_F_SE_INTERCEPT: f64 = %.10f;\n", se[1]))
  cat(sprintf("const CROSS_F_SE_SLOPE: f64 = %.10f;\n", se[2]))
  fmt_vec("CROSS_F_RANEF_A", ranef(m)$a[, 1])
  fmt_vec("CROSS_F_RANEF_B", ranef(m)$b[, 1])
  cat("\n")
}

# ------------------------------------------------------------------ Scenario G
# Nested random intercepts: y ~ x + (1|a/b)  ==  (1|a) + (1|a:b).
{
  set.seed(13)
  na <- 5; nb <- 4; rp <- 6; n <- na * nb * rp
  a <- rep(1:na, each = nb * rp)
  bwithin <- rep(rep(1:nb, each = rp), times = na)
  ab <- (a - 1) * nb + bwithin   # globally-unique nested id
  x <- round(rnorm(n), 4)
  ea <- rnorm(na, 0, 0.8); eab <- rnorm(na * nb, 0, 0.5)
  y <- round(0.5 + 0.4 * x + ea[a] + eab[ab] + rnorm(n, 0, 0.4), 4)
  m <- lmer(y ~ x + (1 | a) + (1 | ab), REML = TRUE,
            control = lmerControl(calc.derivs = FALSE))
  vc <- as.data.frame(VarCorr(m))
  sd_a <- vc$sdcor[vc$grp == "a"]
  sd_ab <- vc$sdcor[vc$grp == "ab"]
  cat("// Scenario G: nested random intercepts, y ~ x + (1|a/b) = (1|a)+(1|a:b), REML\n")
  fmt_vec("X_NEST_G", x)
  fmt_vec("A_NEST_G", a - 1L, "usize")
  fmt_vec("AB_NEST_G", ab - 1L, "usize")
  fmt_vec("Y_NEST_G", y)
  cat(sprintf("const NEST_G_INTERCEPT: f64 = %.10f;\n", fixef(m)[1]))
  cat(sprintf("const NEST_G_SLOPE: f64 = %.10f;\n", fixef(m)[2]))
  cat(sprintf("const NEST_G_SIGMA: f64 = %.10f;\n", sigma(m)))
  cat(sprintf("const NEST_G_SD_A: f64 = %.10f;\n", sd_a))
  cat(sprintf("const NEST_G_SD_AB: f64 = %.10f;\n", sd_ab))
  se <- sqrt(diag(vcov(m)))
  cat(sprintf("const NEST_G_SE_INTERCEPT: f64 = %.10f;\n", se[1]))
  cat(sprintf("const NEST_G_SE_SLOPE: f64 = %.10f;\n", se[2]))
  fmt_vec("NEST_G_RANEF_A", ranef(m)$a[, 1])
  fmt_vec("NEST_G_RANEF_AB", ranef(m)$ab[, 1])
  cat("\n")
}


#!/usr/bin/env Rscript
# =============================================================================
# GLMM validation data generator.
#
# Emits a Rust fixture of `const` arrays for the GLMM solver (`GlmmRegressor`,
# Phases A and B — random intercept and random slopes). Reference fits come from
# lme4:
#   * Gaussian LMM  -> lme4::lmer(..., REML = TRUE)
#   * Poisson GLMM  -> lme4::glmer(..., family = poisson, nAGQ = 0)
#   * Binomial GLMM -> lme4::glmer(..., family = binomial, nAGQ = 0)
#   * Random slope  -> lme4::lmer(y ~ x + (x | g), REML = TRUE)
#
# The Rust solver reproduces the penalized-conditional-mode Laplace estimator,
# which corresponds to glmer's `nAGQ = 0`. The data arrays are emitted verbatim
# so the Rust tests fit exactly the same numbers.
#
# Regenerate with:
#   Rscript tests/r_scripts/generate_glmm_validation.R \
#       > tests/fixtures/glmm_validation.rs
# =============================================================================

suppressMessages(library(lme4))

fmt_vec <- function(name, v, ty = "f64") {
  cat(sprintf("const %s: [%s; %d] = [", name, ty, length(v)))
  if (ty == "usize") {
    cat(paste(sprintf("%d", v), collapse = ", "))
  } else {
    cat(paste(sprintf("%.10f", v), collapse = ", "))
  }
  cat("];\n")
}

cat("// =============================================================================\n")
cat("// GLMM validation data — generated by tests/r_scripts/generate_glmm_validation.R\n")
cat(sprintf("// R version: %s ; lme4: %s\n",
            R.version.string, as.character(packageVersion("lme4"))))
cat("// Gaussian: lmer(REML=TRUE); Poisson/Binomial: glmer(nAGQ=0).\n")
cat("// =============================================================================\n\n")

set.seed(42)

# ------------------------------------------------------------------ Scenario A
# Gaussian LMM, one covariate, random intercept over 8 groups.
{
  J <- 8; ni <- 10; n <- J * ni
  g <- rep(1:J, each = ni)
  x <- round(rnorm(n), 4)
  b <- rnorm(J, 0, 0.8)
  y <- round(1.0 + 0.5 * x + b[g] + rnorm(n, 0, 0.5), 4)
  m <- lmer(y ~ x + (1 | g), REML = TRUE,
            control = lmerControl(calc.derivs = FALSE))
  vc <- as.data.frame(VarCorr(m))
  re <- ranef(m)$g[, 1]
  cat("// Scenario A: Gaussian LMM, y ~ x + (1|g), REML\n")
  fmt_vec("X_LMM_A", x)
  fmt_vec("G_LMM_A", g - 1L, "usize")
  fmt_vec("Y_LMM_A", y)
  cat(sprintf("const LMM_A_INTERCEPT: f64 = %.10f;\n", fixef(m)[1]))
  cat(sprintf("const LMM_A_SLOPE: f64 = %.10f;\n", fixef(m)[2]))
  cat(sprintf("const LMM_A_SIGMA: f64 = %.10f;\n", sigma(m)))
  cat(sprintf("const LMM_A_SD_RANDOM: f64 = %.10f;\n", vc$sdcor[1]))
  cat(sprintf("const LMM_A_LOGLIK: f64 = %.10f;\n", as.numeric(logLik(m))))
  se <- sqrt(diag(vcov(m)))
  cat(sprintf("const LMM_A_SE_INTERCEPT: f64 = %.10f;\n", se[1]))
  cat(sprintf("const LMM_A_SE_SLOPE: f64 = %.10f;\n", se[2]))
  fmt_vec("LMM_A_RANEF", re)
  # Population-level (marginal) prediction Xβ at the training rows, for
  # validating predict_fixed (random effects set to zero).
  fmt_vec("LMM_A_PREDFIXED", as.numeric(predict(m, re.form = NA)))
  cat("\n")
}

# ------------------------------------------------------------------ Scenario B

# Packages: mediation, lavaan, bda.

suppressPackageStartupMessages({
  library(mediation)
  library(lavaan)
  library(bda)
})

fmt <- function(v) paste(sprintf("%.17e", v), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(v)))
scl <- function(name, v) cat(sprintf("pub const %s: f64 = %.17e;\n", name, v))

cat("// Generated by tests/r_scripts/generate_mediation_validation.R -- do not edit.\n")
cat(sprintf("// %s, mediation %s, lavaan %s, bda %s\n", R.version.string,
            packageVersion("mediation"), packageVersion("lavaan"), packageVersion("bda")))

set.seed(223)
n <- 150
x <- rbinom(n, 1, 0.5)
c1 <- rnorm(n)
c2 <- rnorm(n)
m <- 0.5 + 0.8 * x + 0.3 * c1 + rnorm(n)
y <- 1 + 0.4 * x + 0.6 * m - 0.2 * c1 + 0.1 * c2 + rnorm(n)
# A continuous treatment for the treat_value / control_value case
xc <- runif(n, 0, 3)
mc <- 0.2 + 0.5 * xc + 0.3 * c1 + rnorm(n)
yc <- 0.5 + 0.3 * xc + 0.7 * mc + 0.1 * c2 + rnorm(n)
d <- data.frame(x, c1, c2, m, y, xc, mc, yc)

cat(sprintf("pub const N: usize = %d;\n", n))
arr("X", x); arr("C1", c1); arr("C2", c2); arr("M", m); arr("Y", y)
arr("XC", xc); arr("MC", mc); arr("YC", yc)

# Point estimates and OLS inference of the three linear models
fm <- lm(m ~ x + c1 + c2, d)
fy <- lm(y ~ x + m + c1 + c2, d)
ft <- lm(y ~ x + c1 + c2, d)
scl("A", coef(fm)["x"]); scl("SE_A", sqrt(vcov(fm)["x", "x"]))
scl("B", coef(fy)["m"]); scl("SE_B", sqrt(vcov(fy)["m", "m"]))
scl("C_PRIME", coef(fy)["x"]); scl("SE_C_PRIME", sqrt(vcov(fy)["x", "x"]))
scl("COV_B_C_PRIME", vcov(fy)["m", "x"])
scl("C_TOTAL", coef(ft)["x"]); scl("SE_C_TOTAL", sqrt(vcov(ft)["x", "x"]))
scl("R2_MEDIATOR", summary(fm)$r.squared); scl("R2_OUTCOME", summary(fy)$r.squared)

# mediation::mediate, nonparametric bootstrap (percentile and BCa)
emit_med <- function(pre, med) {
  scl(paste0(pre, "_ACME"), med$d0); scl(paste0(pre, "_ADE"), med$z0)
  scl(paste0(pre, "_TOTAL"), med$tau.coef); scl(paste0(pre, "_PROP"), med$n0)
  arr(paste0(pre, "_ACME_CI"), med$d0.ci); arr(paste0(pre, "_ADE_CI"), med$z0.ci)
  arr(paste0(pre, "_TOTAL_CI"), med$tau.ci); arr(paste0(pre, "_PROP_CI"), med$n0.ci)
  scl(paste0(pre, "_ACME_P"), med$d0.p); scl(paste0(pre, "_ADE_P"), med$z0.p)
  scl(paste0(pre, "_TOTAL_P"), med$tau.p); scl(paste0(pre, "_PROP_P"), med$n0.p)
}
sims <- 2000
set.seed(1)
med_perc <- mediate(fm, fy, treat = "x", mediator = "m", boot = TRUE, sims = sims)
emit_med("PERC", med_perc)
# The bootstrap draws themselves, to check the interval and p-value summaries exactly
arr("PERC_ACME_DRAWS", med_perc$d0.sims); arr("PERC_ADE_DRAWS", med_perc$z0.sims)
arr("PERC_TOTAL_DRAWS", med_perc$tau.sims); arr("PERC_PROP_DRAWS", med_perc$n0.sims)
scl("PERC_ACME_SD", sd(med_perc$d0.sims))
set.seed(1)
med_bca <- mediate(fm, fy, treat = "x", mediator = "m", boot = TRUE, boot.ci.type = "bca", sims = sims)
emit_med("BCA", med_bca)
# Same draws as PERC (same seed), so the BCa intervals are checked exactly too
stopifnot(all(med_bca$d0.sims == med_perc$d0.sims))

# Continuous treatment, effect of moving xc from 0.5 to 2
fmc <- lm(mc ~ xc + c1 + c2, d)
fyc <- lm(yc ~ xc + mc + c1 + c2, d)
set.seed(2)
med_c <- mediate(fmc, fyc, treat = "xc", mediator = "mc", boot = TRUE, sims = sims,
                 control.value = 0.5, treat.value = 2)
emit_med("CONT", med_c)

# Quasi-Bayesian Monte Carlo (mediate's default)
set.seed(3)
med_qb <- mediate(fm, fy, treat = "x", mediator = "m", sims = sims)
emit_med("QB", med_qb)

# lavaan: a*b with a bootstrap standard error
lav <- sem("m ~ a*x + c1 + c2\n y ~ b*m + cp*x + c1 + c2\n ab := a*b\n total := cp + a*b",
           data = d, se = "bootstrap", bootstrap = sims, iseed = 4)
pe <- parameterEstimates(lav)
scl("LAVAAN_AB", pe$est[pe$label == "ab"]); scl("LAVAAN_AB_SE", pe$se[pe$label == "ab"])
scl("LAVAAN_TOTAL", pe$est[pe$label == "total"])

# Sobel test (bda::mediation.test has no covariates: use the x, m, y data alone)
sob <- mediation.test(d$m, d$x, d$y)
scl("SOBEL_NOCOV_Z", sob["z.value", "Sobel"]); scl("SOBEL_NOCOV_P", sob["p.value", "Sobel"])

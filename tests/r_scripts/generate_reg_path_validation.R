#!/usr/bin/env Rscript
# Reference values for the ridge / elastic-net paths and k-fold CV
# (`solvers::path`), written to tests/fixtures/reg_path_validation.rs.
#
#   Rscript tests/r_scripts/generate_reg_path_validation.R > tests/fixtures/reg_path_validation.rs
#
# glmnet is not installed on the machine that generated these values, so the
# references are:
#  * `glmnet_ref` below: glmnet's documented Gaussian objective
#      1/(2n) RSS + lambda * ((1 - alpha)/2 ||b||^2 + alpha ||b||_1)
#    with its conventions (columns centred and, with standardize, scaled by the
#    1/n standard deviation; y scaled internally by its 1/n standard deviation
#    and lambda by the same factor; coefficients returned on the original
#    scale). Ridge (alpha = 0) is solved in closed form, alpha > 0 by
#    coordinate descent run to max_j v_j * delta_j^2 < 1e-26.
#  * grpreg (independent solver) with singleton groups, which is the lasso
#    with standardised columns; y is pre-scaled to unit 1/n variance so
#    glmnet's internal y scaling is the identity. (grpreg's alpha = 0.5 path
#    was not used: on this data it violates the KKT conditions at some
#    lambdas, e.g. a zero coefficient with |gradient| > lambda * alpha.)
#  * glmnet's default lambda grid (lambda_max = max|x~'(y - ybar)| / (n max(alpha, 1e-3)),
#    nlambda = 100, lambda.min.ratio = 1e-4 for n > p) and cv.glmnet's
#    aggregates (cvm, cvsd, lambda.min, lambda.1se; getOptcv.glmnet) with
#    fold ids passed in.

suppressPackageStartupMessages(library(grpreg))

fmt <- function(v) paste(sprintf("%.17e", v), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(v)))
num <- function(name, v) cat(sprintf("pub const %s: f64 = %s;\n", name, sprintf("%.17e", v)))
uarr <- function(name, v) cat(sprintf("pub const %s: [usize; %d] = [%s];\n", name, length(v),
                                      paste(v, collapse = ", ")))

glmnet_ref <- function(x, y, lambdas, alpha, standardize, intercept = TRUE, tol = 1e-26) {
  n <- nrow(x); p <- ncol(x)
  xm <- if (intercept) colMeans(x) else rep(0, p)
  ym <- if (intercept) mean(y) else 0
  xc <- sweep(x, 2, xm)
  xs <- if (standardize) sqrt(colMeans(xc^2)) else rep(1, p)
  X <- sweep(xc, 2, xs, "/")
  sy <- sqrt(mean((y - ym)^2))
  Y <- (y - ym) / sy
  v <- colMeans(X^2)
  B <- matrix(0, p, length(lambdas))
  if (alpha == 0) {
    for (l in seq_along(lambdas)) {
      B[, l] <- solve(crossprod(X) / n + diag(lambdas[l] / sy, p), crossprod(X, Y) / n)
    }
  } else {
    soft <- function(z, g) sign(z) * max(abs(z) - g, 0)
    b <- rep(0, p); r <- Y
    for (l in order(-lambdas)) {
      lam <- lambdas[l] / sy
      repeat {
        dmax <- 0
        for (j in 1:p) {
          g <- sum(X[, j] * r) / n + v[j] * b[j]
          new <- soft(g, lam * alpha) / (v[j] + lam * (1 - alpha))
          d <- new - b[j]
          if (d != 0) { r <- r - d * X[, j]; b[j] <- new; dmax <- max(dmax, v[j] * d^2) }
        }
        if (dmax < tol) break
      }
      B[, l] <- b
    }
  }
  beta <- B * sy / xs
  list(beta = beta, a0 = ym - colSums(beta * xm))
}

lambda_grid_ref <- function(x, y, alpha, standardize, nlambda = 100, ratio = 1e-4) {
  n <- nrow(x)
  xc <- sweep(x, 2, colMeans(x))
  if (standardize) xc <- sweep(xc, 2, sqrt(colMeans(xc^2)), "/")
  lmax <- max(abs(crossprod(xc, y - mean(y)))) / (n * max(alpha, 1e-3))
  exp(seq(log(lmax), log(lmax * ratio), length.out = nlambda))
}

cv_ref <- function(x, y, lambdas, foldid, alpha, standardize) {
  K <- max(foldid)
  cvraw <- matrix(NA, K, length(lambdas)); N <- numeric(K)
  for (k in 1:K) {
    tr <- foldid != k
    f <- glmnet_ref(x[tr, , drop = FALSE], y[tr], lambdas, alpha, standardize)
    pred <- sweep(x[!tr, , drop = FALSE] %*% f$beta, 2, f$a0, "+")
    cvraw[k, ] <- colMeans((y[!tr] - pred)^2)
    N[k] <- sum(!tr)
  }
  cvm <- apply(cvraw, 2, weighted.mean, w = N)
  cvsd <- sqrt(apply(scale(cvraw, cvm, FALSE)^2, 2, weighted.mean, w = N) / (K - 1))
  lambda.min <- max(lambdas[cvm <= min(cvm)])
  idmin <- match(lambda.min, lambdas)
  lambda.1se <- max(lambdas[cvm <= (cvm + cvsd)[idmin]])
  list(cvm = cvm, cvsd = cvsd, lambda.min = lambda.min, lambda.1se = lambda.1se)
}

set.seed(20261012)
n <- 60; p <- 4
z <- rnorm(n)
x <- cbind(10 + 3 * rnorm(n), 0.5 * z + 0.2 * rnorm(n), z + 0.4 * rnorm(n), 100 * runif(n))
y <- 3 + 0.8 * x[, 1] - 2 * x[, 2] + 1.5 * x[, 3] + 0.01 * x[, 4] + rnorm(n, sd = 2)
foldid <- sample(rep(1:5, length.out = n))

cat("// Generated by tests/r_scripts/generate_reg_path_validation.R -- do not edit.\n")
cat(sprintf("// %s, grpreg %s (glmnet not installed: documented-objective reference)\n",
            R.version.string, packageVersion("grpreg")))
cat("#![allow(dead_code)]\n\n")
cat(sprintf("pub const N: usize = %d;\npub const P: usize = %d;\n", n, p))
arr("X", as.vector(t(x)))  # row-major
arr("Y", y)
uarr("FOLDID", foldid)

emit_path <- function(prefix, lambdas, fit) {
  arr(paste0(prefix, "_LAMBDA"), lambdas)
  arr(paste0(prefix, "_BETA"), as.vector(fit$beta))  # column-major p x L
  arr(paste0(prefix, "_A0"), fit$a0)
}
emit_cv <- function(prefix, cv) {
  arr(paste0(prefix, "_CVM"), cv$cvm)
  arr(paste0(prefix, "_CVSD"), cv$cvsd)
  num(paste0(prefix, "_LMIN"), cv$lambda.min)
  num(paste0(prefix, "_L1SE"), cv$lambda.1se)
}

for (cfg in list(list("RIDGE", 0, FALSE), list("RIDGE_STD", 0, TRUE),
                 list("ENET", 0.5, FALSE), list("ENET_STD", 0.5, TRUE),
                 list("LASSO_STD", 1, TRUE))) {
  pre <- cfg[[1]]; a <- cfg[[2]]; s <- cfg[[3]]
  cat(sprintf("\n// %s: alpha = %g, standardize = %s, default grid\n", pre, a, s))
  lam <- lambda_grid_ref(x, y, a, s)
  emit_path(pre, lam, glmnet_ref(x, y, lam, a, s))
  if (pre != "LASSO_STD") emit_cv(pre, cv_ref(x, y, lam, foldid, a, s))
}

# grpreg cross-check: unit-variance y, standardised columns.
ys <- (y - mean(y)) / sqrt(mean((y - mean(y))^2))
arr("YS", ys)
for (cfg in list(list("GRP_LASSO", 1))) {
  pre <- cfg[[1]]; a <- cfg[[2]]
  lam <- lambda_grid_ref(x, ys, a, TRUE, nlambda = 30, ratio = 1e-3)
  g <- grpreg(x, ys, group = 1:p, penalty = "grLasso", alpha = a, lambda = lam,
              eps = 1e-12, max.iter = 1e7)
  cf <- coef(g)
  cat(sprintf("\n// %s: grpreg alpha = %g (standardised columns)\n", pre, a))
  arr(paste0(pre, "_LAMBDA"), lam)
  arr(paste0(pre, "_BETA"), as.vector(cf[-1, ]))
  arr(paste0(pre, "_A0"), cf[1, ])
}

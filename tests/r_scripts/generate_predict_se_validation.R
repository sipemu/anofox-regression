# ---- GLMs ----
ctl <- glm.control(epsilon = 1e-14, maxit = 200)
emit_glm <- function(prefix, m, newdata = nd) {
  pl <- predict(m, newdata, type = "link", se.fit = TRUE)
  pr <- predict(m, newdata, type = "response", se.fit = TRUE)
  z <- qnorm(0.975); li <- family(m)$linkinv
  emit(paste0(prefix, "_ETA"), pl$fit); emit(paste0(prefix, "_SE_ETA"), pl$se.fit)
  emit(paste0(prefix, "_MU"), pr$fit); emit(paste0(prefix, "_SE_MU"), pr$se.fit)
  emit(paste0(prefix, "_MU_LWR"), li(pl$fit - z * pl$se.fit))
  emit(paste0(prefix, "_MU_UPR"), li(pl$fit + z * pl$se.fit))
}
m_pois <- glm(yp ~ x1 + x2 + offset(off), family = poisson, control = ctl)
emit_glm("POIS", m_pois)
m_bin <- glm(yb ~ x1 + x2, family = binomial, control = ctl)
emit_glm("BIN", m_bin)
m_gam <- glm(yg ~ x1 + x2, family = Gamma(link = "log"), control = ctl)
emit_glm("GAMMA", m_gam)
m_nb <- glm.nb(ynb ~ x1 + x2, control = glm.control(epsilon = 1e-14, maxit = 200))
emit_glm("NB", m_nb)

# ---- linear models ----
emit_lm <- function(prefix, m) {
  pc <- predict(m, nd, se.fit = TRUE, interval = "confidence", level = 0.95)
  pp <- suppressWarnings(predict(m, nd, se.fit = TRUE, interval = "prediction", level = 0.90))
  emit(paste0(prefix, "_FIT"), pc$fit[, "fit"]); emit(paste0(prefix, "_SE"), pc$se.fit)
  emit(paste0(prefix, "_CONF_LWR"), pc$fit[, "lwr"]); emit(paste0(prefix, "_CONF_UPR"), pc$fit[, "upr"])
  emit(paste0(prefix, "_PRED90_LWR"), pp$fit[, "lwr"]); emit(paste0(prefix, "_PRED90_UPR"), pp$fit[, "upr"])
  emit(paste0(prefix, "_SIGMA"), pc$residual.scale)
}
m_ols <- lm(y_lin ~ x1 + x2)
m_wls <- lm(y_lin ~ x1 + x2, weights = w)
emit_lm("OLS", m_ols); emit_lm("WLS", m_wls)

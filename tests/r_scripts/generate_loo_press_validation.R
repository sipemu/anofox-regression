#!/usr/bin/env Rscript
# Reference values for the leave-one-out (PRESS) diagnostics: Augment::loo_residual,
# Augment::loo_fitted and diagnostics::press (anofox-statistics#220).
# Run from the crate root:
#   Rscript tests/r_scripts/generate_loo_press_validation.R > tests/fixtures/loo_press_validation.rs
# Base R only. Every leave-one-out residual is also checked against an explicit
# refit without the row.

fmt <- function(v) paste(ifelse(is.nan(v), "f64::NAN", sprintf("%.15e", v)), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(v)))
num <- function(name, v) cat(sprintf("pub const %s: f64 = %s;\n", name, sprintf("%.15e", v)))

cat("// Generated by tests/r_scripts/generate_loo_press_validation.R -- do not edit.\n")
cat(sprintf("// %s\n", R.version.string))
cat("#![allow(dead_code)]\n\n")

d <- mtcars
arr("MT_MPG", d$mpg); arr("MT_WT", d$wt); arr("MT_HP", d$hp); arr("MT_W", 1 / d$cyl)

# Leave-one-out prediction error by refitting without row i.
refit_loo <- function(m, data, w = NULL) {
  sapply(seq_len(nrow(data)), function(i) {
    mi <- if (is.null(w)) update(m, data = data[-i, ])
          else update(m, data = data[-i, ], weights = w[-i])
    data$mpg[i] - predict(mi, newdata = data[i, , drop = FALSE])
  })
}

loo <- function(prefix, m, data, w = NULL, intercept = TRUE) {
  h <- hatvalues(m)
  e <- residuals(m)
  loo_res <- e / (1 - h)
  stopifnot(isTRUE(all.equal(unname(loo_res), unname(refit_loo(m, data, w)), tolerance = 1e-10)))
  ww <- if (is.null(w)) rep(1, length(e)) else w
  # R's predictive residual is sqrt(w) times the response-scale LOO residual.
  stopifnot(isTRUE(all.equal(unname(rstandard(m, type = "predictive")),
                             unname(sqrt(ww) * loo_res))))
  press <- sum(rstandard(m, type = "predictive")^2)
  y <- model.response(model.frame(m))
  ybar <- if (intercept) sum(ww * y) / sum(ww) else 0
  sst <- sum(ww * (y - ybar)^2)
  # 1 - RSS/SST is the fit's R-squared under the same SST convention.
  stopifnot(isTRUE(all.equal(1 - sum(ww * e^2) / sst, summary(m)$r.squared)))
  arr(paste0(prefix, "_LOO_RESID"), loo_res)
  arr(paste0(prefix, "_LOO_FITTED"), y - loo_res)
  num(paste0(prefix, "_PRESS"), press)
  num(paste0(prefix, "_PRESS_RMSE"), sqrt(press / length(y)))
  num(paste0(prefix, "_LOO_R2"), 1 - press / sst)
}

cat("\n// OLS: lm(mpg ~ wt + hp, mtcars)\n")
loo("OLS", lm(mpg ~ wt + hp, d), d)
cat("\n// OLS without intercept: lm(mpg ~ 0 + wt + hp, mtcars)\n")
loo("OLS0", lm(mpg ~ 0 + wt + hp, d), d, intercept = FALSE)
cat("\n// WLS: lm(mpg ~ wt + hp, mtcars, weights = 1/cyl)\n")
w <- 1 / d$cyl
loo("WLS", lm(mpg ~ wt + hp, d, weights = w), d, w)

# A dummy with a single 1: that row has leverage 1 and no LOO prediction.
cat("\n// Leverage 1: lm(y ~ x + d), d a single-observation dummy\n")
x <- c(1, 2, 3, 4, 5, 6, 7, 8)
dd <- c(0, 0, 0, 0, 0, 0, 0, 1)
y <- c(1.2, 1.9, 3.2, 3.8, 5.1, 6.2, 6.8, 20)
m <- lm(y ~ x + dd)
h <- hatvalues(m)
stopifnot(h[8] > 1 - 10 * .Machine$double.eps, is.nan(rstandard(m, type = "predictive")[8]))
arr("H1_X", x); arr("H1_D", dd); arr("H1_Y", y)
arr("H1_LOO_RESID", ifelse(seq_along(y) == 8, NaN, residuals(m) / (1 - h)))

#!/usr/bin/env Rscript
# Reference values for quantile-regression inference (`solvers::quantile_inference`),
# written to tests/fixtures/quantile_inference_validation.rs.
#
#   Rscript tests/r_scripts/generate_quantile_inference_validation.R > tests/fixtures/quantile_inference_validation.rs
#
# quantreg::summary.rq(se = "iid" | "nid") coefficient tables (Hall-Sheather
# bandwidth), the regression-quantile process rq(y ~ x, tau = 1:9/10), and an
# xy-pair bootstrap SE (R = 4000) used only as a statistical sanity reference.

suppressPackageStartupMessages(library(quantreg))

fmt <- function(v) paste(sprintf("%.17e", v), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(v)))

set.seed(157)
n <- 120
x1 <- runif(n, 0, 10)
x2 <- rnorm(n)
y <- 1 + 0.7 * x1 - 1.2 * x2 + (0.5 + 0.15 * x1) * rnorm(n)

cat("// Generated by tests/r_scripts/generate_quantile_inference_validation.R -- do not edit.\n")
cat(sprintf("// %s, quantreg %s\n", R.version.string, packageVersion("quantreg")))
cat("#![allow(dead_code)]\n\n")
cat(sprintf("pub const N: usize = %d;\n", n))
arr("X1", x1); arr("X2", x2); arr("Y", y)

taus <- c(0.25, 0.5, 0.75)
arr("TAUS", taus)
for (k in seq_along(taus)) {
  f <- rq(y ~ x1 + x2, tau = taus[k])
  for (se in c("iid", "nid")) {
    s <- summary(f, se = se)$coefficients
    pre <- sprintf("T%d_%s", k, toupper(se))
    arr(paste0(pre, "_COEF"), s[, 1])
    arr(paste0(pre, "_SE"), s[, 2])
    arr(paste0(pre, "_T"), s[, 3])
    arr(paste0(pre, "_P"), s[, 4])
  }
}

set.seed(1)
fb <- summary(rq(y ~ x1 + x2, tau = 0.5), se = "boot", bsmethod = "xy", R = 4000)$coefficients
arr("BOOT_MEDIAN_SE", fb[, 2])

ptaus <- 1:9 / 10
arr("PROCESS_TAUS", ptaus)
arr("PROCESS_COEF", as.vector(coef(rq(y ~ x1 + x2, tau = ptaus))))  # 3 x 9 column-major

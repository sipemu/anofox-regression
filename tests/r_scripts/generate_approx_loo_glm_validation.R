#!/usr/bin/env Rscript
# Reference values for the one-step approximate leave-one-out fields of the GLM
# augment (Augment::approx_loo_fitted / approx_loo_residual,
# anofox-statistics#235).
# Run from the crate root:
#   Rscript tests/r_scripts/generate_approx_loo_glm_validation.R > tests/fixtures/approx_loo_glm_validation.rs
#   cargo fmt
# Base R only. The approximation is R's one-step coefficient change
# influence(fit)$coefficients (Pregibon 1981): eta_(i) = x_i'(beta - dbeta_i).
# It is checked against the closed form eta_i - h_i z_i / (1 - h_i), and the
# exact refits without each row are written out too, so the test can show how
# close the approximation is.

fmt <- function(v) paste(ifelse(is.nan(v), "f64::NAN", sprintf("%.15e", v)), collapse = ", ")
arr <- function(name, v) cat(sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v), fmt(unname(v))))

cat("// Generated by tests/r_scripts/generate_approx_loo_glm_validation.R -- do not edit.\n")
cat(sprintf("// %s\n", R.version.string))
cat("#![allow(dead_code)]\n\n")

d <- mtcars
arr("MT_WT", d$wt); arr("MT_HP", d$hp)
arr("MT_CARB", d$carb); arr("MT_VS", d$vs); arr("MT_MPG", d$mpg)

approx <- function(prefix, m, yname) {
  ctl <- glm.control(epsilon = 1e-14, maxit = 100)
  m <- update(m, control = ctl)
  X <- model.matrix(m)
  eta <- predict(m, type = "link")
  dbeta <- influence(m, do.coef = TRUE)$coefficients
  eta_loo <- eta - rowSums(X * dbeta)
  # Closed form on the working scale.
  h <- hatvalues(m)
  mu <- fitted(m)
  z <- (d[[yname]] - mu) / m$family$mu.eta(eta)
  stopifnot(isTRUE(all.equal(unname(eta_loo), unname(eta - h * z / (1 - h)), tolerance = 1e-10)))
  mu_loo <- m$family$linkinv(eta_loo)
  refit <- sapply(seq_len(nrow(d)), function(i) {
    predict(update(m, data = d[-i, ]), newdata = d[i, , drop = FALSE], type = "response")
  })
  arr(paste0(prefix, "_FITTED"), mu)
  arr(paste0(prefix, "_APPROX_LOO_FITTED"), mu_loo)
  arr(paste0(prefix, "_APPROX_LOO_RESID"), d[[yname]] - mu_loo)
  arr(paste0(prefix, "_REFIT_LOO_FITTED"), refit)
}

cat("\n// Poisson: glm(carb ~ wt + hp, poisson, mtcars)\n")
approx("POIS", glm(carb ~ wt + hp, poisson, d), "carb")
cat("\n// Logistic: glm(vs ~ mpg + wt, binomial, mtcars)\n")
approx("LOGIT", glm(vs ~ mpg + wt, binomial, d), "vs")
cat("\n// Gamma, log link: glm(mpg ~ wt + hp, Gamma(\"log\"), mtcars)\n")
approx("GAMMA", glm(mpg ~ wt + hp, Gamma("log"), d), "mpg")

# Issue #308: prior weights for the Poisson, Gamma and Tweedie GLMs,
# reference values from glm(weights = ).
# Run: Rscript tests/r_scripts/generate_glm_weights_validation.R > tests/fixtures/glm_weights_validation.rs
suppressMessages(library(statmod))
set.seed(308)
n <- 40
x1 <- round(rnorm(n), 3)
x2 <- round(runif(n, -1, 1), 3)
w <- round(runif(n, 0.2, 3), 2)
w[7] <- 0
mu <- exp(0.5 + 0.4 * x1 - 0.6 * x2)
y_pois <- rpois(n, mu)
y_gamma <- round(rgamma(n, shape = 3, scale = mu / 3), 4)
y_tw <- round(rtweedie_like <- ifelse(runif(n) < 0.3, 0, rgamma(n, shape = 2, scale = mu / 2)), 4)
y_gauss <- round(1 + 2 * x1 - x2 + rnorm(n, sd = 0.5 / sqrt(pmax(w, 0.2))), 4)

emit <- function(name, v) cat(sprintf("const %s: [f64; %d] = [%s];\n", name, length(v),
  paste(num(v), collapse = ", ")))
fmt <- function(v) { s <- sprintf("%.17g", v); ifelse(grepl("[.eE]", s), s, paste0(s, ".0")) }
num <- function(v) ifelse(is.na(v), "f64::NAN", ifelse(is.infinite(v), ifelse(v > 0, "f64::INFINITY", "f64::NEG_INFINITY"), fmt(v)))

emit1 <- function(name, v) cat(sprintf("const %s: f64 = %s;\n", name, num(v)))

cat("// Generated by tests/r_scripts/generate_glm_weights_validation.R\n")
cat(sprintf("// %s\n", R.version.string))
emit("X1", x1); emit("X2", x2); emit("W", w)
emit("Y_POIS", y_pois); emit("Y_GAMMA", y_gamma); emit("Y_TW", y_tw); emit("Y_GAUSS", y_gauss)

ctl <- glm.control(epsilon = 1e-14, maxit = 200)
out <- function(tag, fit, disp_fixed = FALSE) {
  s <- summary(fit)
  emit(paste0(tag, "_COEF"), coef(fit))
  emit(paste0(tag, "_SE"), s$coefficients[, 2])
  emit1(paste0(tag, "_DEV"), deviance(fit))
  emit1(paste0(tag, "_NULL_DEV"), fit$null.deviance)
  emit1(paste0(tag, "_DISP"), s$dispersion)
  emit1(paste0(tag, "_DF_RESID"), fit$df.residual)
  ll <- tryCatch(as.numeric(logLik(fit)), error = function(e) NaN)
  emit1(paste0(tag, "_LOGLIK"), ll)
  emit1(paste0(tag, "_AIC"), ifelse(is.finite(ll), AIC(fit), NaN))
  emit1(paste0(tag, "_BIC"), ifelse(is.finite(ll), BIC(fit), NaN))
  emit(paste0(tag, "_PEARSON"), residuals(fit, type = "pearson"))
  emit(paste0(tag, "_DEVRES"), residuals(fit, type = "deviance"))
}
out("POIS", glm(y_pois ~ x1 + x2, family = poisson, weights = w, control = ctl))
out("QPOIS", glm(y_pois ~ x1 + x2, family = quasipoisson, weights = w, control = ctl))
out("GAMMA", glm(y_gamma ~ x1 + x2, family = Gamma(link = "log"), weights = w, control = ctl))
out("TW", glm(y_tw ~ x1 + x2, family = tweedie(var.power = 1.5, link.power = 0), weights = w, control = ctl))
out("GAUSS", glm(y_gauss ~ x1 + x2, family = gaussian, weights = w, control = ctl))
out("IG", glm(y_gamma ~ x1 + x2, family = inverse.gaussian(link = "log"), weights = w, control = ctl))
wp <- pmax(w, 0.5)
emit("WP", wp)
out("GAUSSP", glm(y_gauss ~ x1 + x2, family = gaussian, weights = wp, control = ctl))

fn data() -> (Mat<f64>, Col<f64>) {
    let x = Mat::from_fn(N, 4, |i, j| [X0[i], X1[i], X2[i], X3[i]][j]);
    (x, Col::from_fn(N, |i| Y[i]))
}

fn close(a: f64, b: f64, tol: f64, what: &str) {
    assert!(
        (a - b).abs() < tol * (1.0 + b.abs()),
        "{what}: {a} vs R {b}"
    );
}

fn check(
    intercept: bool,
    scale: bool,
    explvar: &[f64; 2],
    coef: &[f64; 4],
    fitted: &[f64; N],
    what: &str,
) {
    let (x, y) = data();
    let fit = PlsRegressor::builder()
        .n_components(2)
        .with_intercept(intercept)
        .scale(scale)
        .build()
        .fit(&x, &y)
        .unwrap();
    let ev = fit.explained_variance_ratio();
    for k in 0..2 {
        close(ev[k], explvar[k], 1e-9, &format!("{what} explvar {k}"));
    }
    for (j, &want) in coef.iter().enumerate().take(4) {
        close(
            fit.coefficients()[j],
            want,
            1e-9,
            &format!("{what} coef {j}"),
        );
    }
    for (i, &want) in fitted.iter().enumerate().take(N) {
        close(
            fit.result().fitted_values[i],
            want,
            1e-9,
            &format!("{what} fitted {i}"),
        );
    }
}

#[test]
fn centred_matches_plsr() {
    check(
        true,
        false,
        &CENTER_EXPLVAR,
        &CENTER_COEF,
        &CENTER_FITTED,
        "centred",
    );
}

#[test]
fn scaled_matches_plsr() {
    check(
        true,
        true,
        &SCALE_EXPLVAR,
        &SCALE_COEF,
        &SCALE_FITTED,
        "scaled",
    );
}

#[test]
fn without_intercept_matches_plsr_center_false() {
    check(
        false,
        false,
        &NOCENTER_EXPLVAR,
        &NOCENTER_COEF,
        &NOCENTER_FITTED,
        "no centring",
    );
}

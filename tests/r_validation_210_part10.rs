#[test]
fn robcov_and_lr_test_match_orm() {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let y = Col::from_fn(N, |i| Y[i]);
    for (link, robcov, lr) in [
        (OrdinalLink::Logistic, &LOGISTIC_ROBCOV, &LOGISTIC_LR),
        (OrdinalLink::Probit, &PROBIT_ROBCOV, &PROBIT_LR),
    ] {
        let f = OrdinalRegressor::builder()
            .link(link)
            .tolerance(1e-13)
            .build()
            .fit(&x, &y)
            .unwrap();
        let v = f
            .cluster_vcov(&x, &y, &[&CLUSTER], &ClusterOptions::robcov())
            .unwrap();
        for a in 0..5 {
            for b in 0..5 {
                close(
                    &format!("{link:?} robcov {a},{b}"),
                    v[(a, b)],
                    robcov[a * 5 + b],
                    1e-8,
                );
            }
        }
        close(&format!("{link:?} LR"), f.lr_chisq(), lr[0], 1e-8);
        close(&format!("{link:?} LR df"), f.effective_df(), lr[1], 1e-12);
        close(&format!("{link:?} LR p"), f.lr_p_value(), lr[2], 1e-8);
        // the scores sum to zero at the estimate
        let u = f.score_contributions(&x, &y).unwrap();
        for j in 0..5 {
            let s: f64 = (0..N).map(|i| u[(i, j)]).sum();
            assert!(s.abs() < 1e-8, "{link:?} score {j} sums to {s}");
        }
    }
}

#[test]
fn score_contributions_reject_bad_input() {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let y = Col::from_fn(N, |i| Y[i]);
    let f = OrdinalRegressor::builder().build().fit(&x, &y).unwrap();
    assert!(f.score_contributions(&Mat::zeros(N, 3), &y).is_err());
    let mut y2 = y.clone();
    y2[0] = 7.5;
    assert!(f.score_contributions(&x, &y2).is_err());
}

#[test]
fn pentrace_on_an_ordinal_response_matches_rms() {
    const NP: usize = 300;
    const P: usize = 9;
    let mut t = TermMap::new();
    let z1 = t.add_main("z1", &[false, true, true]);
    let z2 = t.add_main("z2", &[false]);
    let g = t.add_main("g", &[false, false]);
    t.add_interaction(z1, z2, false).unwrap();
    let x = Mat::from_fn(NP, P, |i, j| PT_X[i * P + j]);
    let y = Col::from_fn(NP, |i| PT_Y[i]);
    let grid = penalty_grid(&[0.0, 2.0], &[0.0, 4.0, 16.0], &[], &[]);
    let tr = pentrace(
        &x,
        &y,
        &t,
        &[g],
        &grid,
        OrdinalLink::Logistic,
        PentraceCriterion::CorrectedAic,
    )
    .unwrap();
    assert_eq!(tr.rows.len(), PT_STATS.len() / 6);
    for (i, row) in tr.rows.iter().enumerate() {
        let r = &PT_STATS[6 * i..6 * i + 6];
        assert_eq!(
            (row.penalty.simple, row.penalty.nonlinear),
            (r[0], Some(r[1]))
        );
        close(&format!("row {i} df"), row.df, r[2], 1e-5);
        close(&format!("row {i} aic"), row.aic, r[3], 1e-5);
        close(&format!("row {i} bic"), row.bic, r[4], 1e-5);
        close(&format!("row {i} aic.c"), row.aic_c, r[5], 1e-5);
    }
    let best = tr.rows[tr.best].penalty;
    assert_eq!(
        (best.simple, best.nonlinear),
        (PT_BEST[0], Some(PT_BEST[1]))
    );
}

#[test]
fn alm_with_non_canonical_links_matches_glm() {
    let m = XC.len();
    let x = Mat::from_fn(m, 1, |i, _| XC[i]);
    for (dist, link, y, want) in [
        (
            AlmDistribution::Poisson,
            LinkFunction::Sqrt,
            &YC[..],
            &POIS_SQRT,
        ),
        (
            AlmDistribution::Poisson,
            LinkFunction::Identity,
            &YC,
            &POIS_IDENTITY,
        ),
        (
            AlmDistribution::Binomial,
            LinkFunction::Probit,
            &YB,
            &BIN_PROBIT,
        ),
        (
            AlmDistribution::Binomial,
            LinkFunction::Cloglog,
            &YB,
            &BIN_CLOGLOG,
        ),
    ] {
        let f = AlmRegressor::builder()
            .distribution(dist)
            .link(link)
            .tolerance(1e-12)
            .build()
            .fit(&x, &Col::from_fn(m, |i| y[i]))
            .unwrap();
        let r = f.result();
        let got = [r.intercept.unwrap(), r.coefficients[0], r.log_likelihood];
        for (k, (g, w)) in got.iter().zip(want.iter()).enumerate() {
            assert!(
                (g - w).abs() <= 1e-6 * (1.0 + w.abs()),
                "{dist:?} {link:?}[{k}]: {g} vs glm {w}"
            );
        }
    }
}

fn check(dist: AlmDistribution, weights: &[f64], dynamic: &[f64], tol: f64) {
    let n = Y.len();
    let x = Mat::from_fn(n, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let f = LmDynamicRegressor::builder()
        .ic(InformationCriterion::AICc)
        .distribution(dist)
        .lowess_span(0.5)
        .build()
        .fit(&x, &Col::from_fn(n, |i| Y[i]))
        .unwrap();
    let w = f.smoothed_weights().unwrap();
    let m = w.ncols();
    for i in 0..n {
        for j in 0..m {
            let (g, e) = (w[(i, j)], weights[i * m + j]);
            assert!(
                (g - e).abs() <= tol * (1.0 + e.abs()),
                "{dist:?} weight [{i},{j}]: {g} vs {e}"
            );
        }
    }
    let d = f.dynamic_coefficients();
    for i in 0..n {
        for j in 0..3 {
            let (g, e) = (d[(i, j)], dynamic[i * 3 + j]);
            assert!(
                (g - e).abs() <= tol * (1.0 + e.abs()),
                "{dist:?} coef [{i},{j}]: {g} vs {e}"
            );
        }
    }
}


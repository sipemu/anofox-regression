#[test]
fn lar_and_lasso_paths_match_lars() {
    let x = Mat::from_fn(40, 4, |i, j| X[i * 4 + j]);
    let y = Col::from_fn(40, |i| Y[i]);
    for (m, lambda, beta) in [
        (LarsMethod::Lar, LAR_LAMBDA, LAR_BETA),
        (LarsMethod::Lasso, LASSO_LAMBDA, LASSO_BETA),
    ] {
        let f = LarsRegressor::builder()
            .method(m)
            .build()
            .fit(&x, &y)
            .unwrap();
        let alphas = f.alphas();
        assert_eq!(alphas.len(), lambda.len() + 1, "{m:?} steps");
        for k in 0..lambda.len() {
            assert!(
                (alphas[k] - lambda[k]).abs() < 1e-10 * lambda[k],
                "{m:?} alpha[{k}]: {} vs {}",
                alphas[k],
                lambda[k]
            );
        }
        assert!(alphas[lambda.len()].abs() < 1e-10);
        let path = f.coefs_path();
        assert_eq!(path.len() * 4, beta.len(), "{m:?} path rows");
        for (s, row) in path.iter().enumerate() {
            for j in 0..4 {
                let want = beta[s * 4 + j];
                assert!(
                    (row[j] - want).abs() < 1e-10 * (1.0 + want.abs()),
                    "{m:?} step {s} coef {j}: {} vs {want}",
                    row[j]
                );
            }
        }
    }
}

fn check(
    ic: InformationCriterion,
    x1: &[f64],
    x2: &[f64],
    y: &[f64],
    crit: &[f64],
    greybox: &[f64; 2],
    what: &str,
) {
    let n = y.len();
    let x = Mat::from_fn(n, 2, |i, j| if j == 0 { x1[i] } else { x2[i] });
    let f = LmDynamicRegressor::builder()
        .ic(ic)
        .build()
        .fit(&x, &Col::from_fn(n, |i| y[i]))
        .unwrap();
    for (k, (&g, &want)) in GRID.iter().zip(crit).enumerate() {
        let got = f.span_criterion(g);
        assert!(
            (got - want).abs() < 1e-9 * want.abs(),
            "{what} criterion[{k}] at {g}: {got} vs {want}"
        );
    }
    let span = f.span().unwrap();
    let at_greybox = f.span_criterion(greybox[0]);
    assert!(
        (at_greybox - greybox[1]).abs() < 1e-9 * greybox[1].abs(),
        "{what} criterion at greybox's f"
    );
    assert!(
        f.span_criterion(span) <= at_greybox + 1e-9,
        "{what}: span {span} vs greybox {}",
        greybox[0]
    );
    assert!(
        (span - greybox[0]).abs() < 0.1,
        "{what}: span {span} vs greybox {}",
        greybox[0]
    );
}


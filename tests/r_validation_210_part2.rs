fn close(a: f64, b: f64, tol: f64, what: &str) {
    assert!(
        (a - b).abs() <= tol * (1.0 + b.abs()),
        "{what}: {a} vs R {b}"
    );
}

fn x() -> Mat<f64> {
    Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] })
}

#[test]
fn aft_information_criteria_and_wald_table_match_survreg() {
    use AftDistribution as D;
    let event: Vec<bool> = EVENT.iter().map(|&e| e == 1.0).collect();
    let cases = [
        (
            D::Weibull,
            WEIBULL_IC,
            WEIBULL_Z,
            WEIBULL_P,
            WEIBULL_CI_LO,
            WEIBULL_CI_HI,
        ),
        (
            D::LogNormal,
            LOGNORMAL_IC,
            LOGNORMAL_Z,
            LOGNORMAL_P,
            LOGNORMAL_CI_LO,
            LOGNORMAL_CI_HI,
        ),
        (
            D::LogLogistic,
            LOGLOGISTIC_IC,
            LOGLOGISTIC_Z,
            LOGLOGISTIC_P,
            LOGLOGISTIC_CI_LO,
            LOGLOGISTIC_CI_HI,
        ),
        (
            D::Exponential,
            EXPONENTIAL_IC,
            EXPONENTIAL_Z,
            EXPONENTIAL_P,
            EXPONENTIAL_CI_LO,
            EXPONENTIAL_CI_HI,
        ),
    ];
    for (dist, ic, z, p, lo, hi) in cases {
        let f = AftRegressor::builder()
            .distribution(dist)
            .compute_inference(true)
            .tolerance(1e-12)
            .build()
            .fit(&x(), &Col::from_fn(N, |i| TIME[i]), &event)
            .unwrap();
        let what = format!("{dist:?}");
        close(f.aic(), ic[0], 1e-8, &format!("{what} AIC"));
        close(f.bic(), ic[1], 1e-8, &format!("{what} BIC"));
        let inf = f.inference().unwrap();
        let gz = [
            inf.intercept_z_value.unwrap(),
            inf.z_values[0],
            inf.z_values[1],
        ];
        let gp = [
            inf.intercept_p_value.unwrap(),
            inf.p_values[0],
            inf.p_values[1],
        ];
        let gl = [
            inf.intercept_ci_lower.unwrap(),
            inf.ci_lower[0],
            inf.ci_lower[1],
        ];
        let gh = [
            inf.intercept_ci_upper.unwrap(),
            inf.ci_upper[0],
            inf.ci_upper[1],
        ];
        for k in 0..3 {
            close(gz[k], z[k], 1e-5, &format!("{what} z[{k}]"));
            close(gp[k], p[k], 1e-5, &format!("{what} p[{k}]"));
            close(gl[k], lo[k], 1e-6, &format!("{what} ci lower[{k}]"));
            close(gh[k], hi[k], 1e-6, &format!("{what} ci upper[{k}]"));
        }
    }
}

#[test]
fn ordinal_probabilities_match_orm() {
    let y = Col::from_fn(N, |i| YO[i]);
    let nd = Mat::from_fn(3, 2, |i, j| if j == 0 { NEW_X1[i] } else { NEW_X2[i] });
    let cases = [
        (OrdinalLink::Logistic, ORM_LOGISTIC_IND, ORM_LOGISTIC_EXC),
        (OrdinalLink::Probit, ORM_PROBIT_IND, ORM_PROBIT_EXC),
        (OrdinalLink::CLogLog, ORM_CLOGLOG_IND, ORM_CLOGLOG_EXC),
    ];
    for (link, ind, exc) in cases {
        let f = OrdinalRegressor::builder()
            .link(link)
            .build()
            .fit(&x(), &y)
            .unwrap();
        let pi = f.category_probabilities(&nd);
        let pe = f.exceedance_probabilities(&nd);
        for i in 0..3 {
            for j in 0..4 {
                close(
                    pi[(i, j)],
                    ind[i * 4 + j],
                    1e-7,
                    &format!("{link:?} P(Y = {}) row {i}", j + 1),
                );
            }
            for j in 0..3 {
                close(
                    pe[(i, j)],
                    exc[i * 3 + j],
                    1e-7,
                    &format!("{link:?} P(Y >= {}) row {i}", j + 2),
                );
            }
        }
    }
}

fn assert_close(got: &[f64], want: &[f64], tol: f64, what: &str) {
    for (k, (g, w)) in got.iter().zip(want).enumerate() {
        assert!(
            (g - w).abs() <= tol * (1.0 + w.abs()),
            "{what}[{k}]: {g} vs R {w}"
        );
    }
}

fn xm(v: &[f64]) -> Mat<f64> {
    Mat::from_fn(v.len(), 1, |i, _| v[i])
}

fn yc(v: &[f64]) -> Col<f64> {
    Col::from_fn(v.len(), |i| v[i])
}

fn x_ridge() -> Mat<f64> {
    Mat::from_fn(50, 3, |i, j| X_RIDGE[i + j * 50])
}

#[test]
fn wls_matches_lm() {
    let f = WlsRegressor::builder()
        .with_intercept(true)
        .weights(yc(&W_WLS))
        .compute_inference(true)
        .build()
        .fit(&xm(&X_WLS), &yc(&Y_WLS))
        .unwrap();
    let r = f.result();
    let got = [
        r.intercept.unwrap(),
        r.coefficients[0],
        r.intercept_std_error.unwrap(),
        r.std_errors.as_ref().unwrap()[0],
        r.r_squared,
    ];
    assert_close(&got, &WLS, 1e-10, "wls");
}

#[test]
fn ridge_matches_closed_form() {
    let f = RidgeRegressor::builder()
        .with_intercept(true)
        .lambda(0.5)
        .build()
        .fit(&x_ridge(), &yc(&Y_RIDGE))
        .unwrap();
    let r = f.result();
    let got = [
        r.intercept.unwrap(),
        r.coefficients[0],
        r.coefficients[1],
        r.coefficients[2],
    ];
    assert_close(&got, &RIDGE, 1e-10, "ridge");
}

#[test]
fn elastic_net_matches_glmnet() {
    let f = ElasticNetRegressor::builder()
        .with_intercept(true)
        .lambda(0.3)
        .alpha(0.5)
        .lambda_scaling(LambdaScaling::Glmnet)
        .tolerance(1e-20)
        .build()
        .fit(&x_ridge(), &yc(&Y_RIDGE))
        .unwrap();
    let r = f.result();
    let got = [
        r.intercept.unwrap(),
        r.coefficients[0],
        r.coefficients[1],
        r.coefficients[2],
    ];
    assert_close(&got, &ENET, 1e-9, "elastic net");
}

/// Intercept, slope, their SEs and the deviance of a log-link Tweedie fit.
fn check_tweedie(p: f64, x: &[f64], y: &[f64], want: &[f64; 5], tol: f64, what: &str) {
    let f = TweedieRegressor::builder()
        .var_power(p)
        .link_power(0.0)
        .with_intercept(true)
        .compute_inference(true)
        .tolerance(1e-13)
        .build()
        .fit(&xm(x), &yc(y))
        .unwrap();
    let r = f.result();
    let got = [
        r.intercept.unwrap(),
        r.coefficients[0],
        r.intercept_std_error.unwrap(),
        r.std_errors.as_ref().unwrap()[0],
        f.deviance,
    ];
    assert_close(&got, want, tol, what);
}

#[test]
fn tweedie_fits_match_converged_r() {
    let gamma = (&X_TWEEDIE_GAMMA, &Y_TWEEDIE_GAMMA, &TWEEDIE_GAMMA);
    check_tweedie(2.0, gamma.0, gamma.1, gamma.2, 1e-7, "gamma");
    let pois = (&X_TWEEDIE_POISSON, &Y_TWEEDIE_POISSON, &TWEEDIE_POISSON);
    check_tweedie(1.0, pois.0, pois.1, pois.2, 1e-7, "poisson");
    let ig = (&X_TWEEDIE_INVGAUSS, &Y_TWEEDIE_INVGAUSS, &TWEEDIE_INVGAUSS);
    check_tweedie(3.0, ig.0, ig.1, ig.2, 1e-7, "inverse gaussian");
    let cpg = (&X_TWEEDIE_CPG, &Y_TWEEDIE_CPG, &TWEEDIE_CPG);
    check_tweedie(1.5, cpg.0, cpg.1, cpg.2, 1e-7, "compound Poisson-gamma");
}

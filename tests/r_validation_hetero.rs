const WHITE3: [f64; 3] = [13.785556529608751, 9.0, 0.13016048248453604];
const BPZ_KOENKER: [f64; 3] = [2.1387833214469922, 2.0, 0.34321724645462603];
const BPZ_CLASSIC: [f64; 3] = [3.4251893097728598, 2.0, 0.18039711659372354];

const N: usize = 60;

#[test]
fn white_and_custom_breusch_pagan_match_lmtest() {
    let x = Mat::from_fn(N, 3, |i, j| [X1[i], X2[i], X3[i]][j]);
    let z = Mat::from_fn(N, 2, |i, j| [Z1[i], Z2[i]][j]);
    let fit = OlsRegressor::builder()
        .build()
        .fit(&x, &Col::from_fn(N, |i| Y[i]))
        .unwrap();
    let e = &fit.result().residuals;
    for (label, got, want) in [
        ("White (3 regressors)", white_test(e, &x).unwrap(), WHITE3),
        (
            "bptest(~ z1 + z2)",
            breusch_pagan(e, &z, true).unwrap(),
            BPZ_KOENKER,
        ),
        (
            "bptest(~ z1 + z2, studentize = FALSE)",
            breusch_pagan(e, &z, false).unwrap(),
            BPZ_CLASSIC,
        ),
    ] {
        assert!(
            (got.statistic - want[0]).abs() < 1e-9 * want[0],
            "{label} statistic {} vs {}",
            got.statistic,
            want[0]
        );
        assert_eq!(got.df, want[1], "{label} df");
        assert!(
            (got.p_value - want[2]).abs() < 1e-10,
            "{label} p {} vs {}",
            got.p_value,
            want[2]
        );
    }
}

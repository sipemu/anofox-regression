const N: usize = 30;

fn close(a: f64, b: f64, what: &str) {
    assert!(
        (a - b).abs() < 1e-10 * (1.0 + b.abs()),
        "{what}: {a} vs R {b}"
    );
}

#[test]
fn lowess_smooth_matches_r_lowess() {
    let y = Col::from_fn(N, |i| Y[i]);
    for (span, expected) in [(0.3, &F03_SMOOTH), (2.0 / 3.0, &F067_SMOOTH)] {
        let s = lowess_smooth(&y, span);
        for i in 0..N {
            close(s[i], expected[i], &format!("f = {span}, i = {i}"));
        }
    }
}

#[test]
fn lowess_smooth_weights_matches_r_lowess_per_column() {
    let w = Mat::from_fn(N, 3, |i, j| W[i * 3 + j]);
    for (span, expected) in [(0.3, &F03_WEIGHTS), (2.0 / 3.0, &F067_WEIGHTS)] {
        let s = lowess_smooth_weights(&w, span);
        for i in 0..N {
            for j in 0..3 {
                close(
                    s[(i, j)],
                    expected[i * 3 + j],
                    &format!("f = {span}, [{i}, {j}]"),
                );
            }
        }
    }
}

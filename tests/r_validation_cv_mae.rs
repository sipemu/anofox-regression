fn check(alpha: f64, lam: &[f64], cvm: &[f64], cvsd: &[f64], sel: &[f64; 2], what: &str) {
    let x = Mat::from_fn(60, 4, |i, j| X_FLAT[i * 4 + j]);
    let y = Col::from_fn(60, |i| Y[i]);
    let mut opts = PathOptions::elastic_net(alpha);
    opts.tol = 1e-20;
    let cv = cv_path_splits(
        &x,
        &y,
        lam,
        &splits_from_fold_ids(&FOLDID),
        &opts,
        CvMetric::Mae,
    )
    .unwrap();
    for l in 0..lam.len() {
        assert!(
            (cv.cv_mean[l] - cvm[l]).abs() < 1e-9,
            "{what} cvm[{l}]: {} vs {}",
            cv.cv_mean[l],
            cvm[l]
        );
        assert!(
            (cv.cv_se[l] - cvsd[l]).abs() < 1e-9,
            "{what} cvsd[{l}]: {} vs {}",
            cv.cv_se[l],
            cvsd[l]
        );
    }
    assert_eq!(cv.lambda_min, sel[0], "{what} lambda.min");
    assert_eq!(cv.lambda_1se, sel[1], "{what} lambda.1se");
    assert_eq!(cv.n_folds, 5);
}

#[test]
fn mae_cv_matches_cv_glmnet() {
    check(
        1.0,
        &LASSO_LAMBDA,
        &LASSO_CVM,
        &LASSO_CVSD,
        &LASSO_LMIN_L1SE,
        "lasso",
    );
    check(
        0.5,
        &ENET_LAMBDA,
        &ENET_CVM,
        &ENET_CVSD,
        &ENET_LMIN_L1SE,
        "elastic net",
    );
}

const T50_LOSS: f64 = 8779.9663238128469;
const T50_R1: f64 = 0.62055596194577212;
const T50_W_COEF: [f64; 2] = [97.111799436536131, 0.54889627923332063];
const T50_W_LOSS: f64 = 13765.470724283117;
const T50_W_R1: f64 = 0.61468975992504493;
const T90_LOSS: f64 = 3391.9837110282483;
const T90_R1: f64 = 0.76471461452942668;
const T90_W_COEF: [f64; 2] = [70.429589383156582, 0.68386418432454799];
const T90_W_LOSS: f64 = 5333.3312696126031;
const T90_W_R1: f64 = 0.76002105207898696;

const N: usize = 235;

fn close(a: f64, b: f64, tol: f64, what: &str) {
    assert!(
        (a - b).abs() < tol * (1.0 + b.abs()),
        "{what}: {a} vs R {b}"
    );
}

#[test]
fn loss_and_r1_match_rq() {
    let x = Mat::from_fn(N, 1, |i, _| X[i]);
    let y = Col::from_fn(N, |i| Y[i]);
    let cases = [
        (0.05, T05_LOSS, T05_R1, T05_W_COEF, T05_W_LOSS, T05_W_R1),
        (0.3, T30_LOSS, T30_R1, T30_W_COEF, T30_W_LOSS, T30_W_R1),
        (0.5, T50_LOSS, T50_R1, T50_W_COEF, T50_W_LOSS, T50_W_R1),
        (0.9, T90_LOSS, T90_R1, T90_W_COEF, T90_W_LOSS, T90_W_R1),
    ];
    for (tau, loss, r1, w_coef, w_loss, w_r1) in cases {
        let fit = QuantileRegressor::builder()
            .tau(tau)
            .build()
            .fit(&x, &y)
            .unwrap();
        close(fit.check_loss(), loss, 1e-9, &format!("tau {tau} loss"));
        close(fit.pseudo_r_squared(), r1, 1e-9, &format!("tau {tau} R1"));

        let fit = QuantileRegressor::builder()
            .tau(tau)
            .weights(Col::from_fn(N, |i| W[i]))
            .build()
            .fit(&x, &y)
            .unwrap();
        close(
            fit.intercept().unwrap(),
            w_coef[0],
            1e-8,
            &format!("tau {tau} weighted intercept"),
        );
        close(
            fit.coefficients()[0],
            w_coef[1],
            1e-8,
            &format!("tau {tau} weighted slope"),
        );
        close(
            fit.check_loss(),
            w_loss,
            1e-9,
            &format!("tau {tau} weighted loss"),
        );
        close(
            fit.pseudo_r_squared(),
            w_r1,
            1e-9,
            &format!("tau {tau} weighted R1"),
        );
    }
}

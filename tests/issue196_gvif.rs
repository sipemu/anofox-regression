fn close(a: f64, b: f64, what: &str) {
    assert!(
        (a - b).abs() < 1e-9 * (1.0 + b.abs()),
        "{what}: {a} vs car {b}"
    );
}

#[test]
fn vif_matches_car() {
    let x = Mat::from_fn(N, 4, |i, j| [WT[i], HP[i], DISP[i], DRAT[i]][j]);
    let vif = variance_inflation_factor(&x);
    for j in 0..4 {
        close(vif[j], VIF_PLAIN[j], "VIF");
    }
}

#[test]
fn gvif_matches_car() {
    // wt | cyl6, cyl8 | hp | gear4, gear5 (treatment dummies, as model.matrix)
    let dummy = |v: f64, level: f64| f64::from(u8::from(v == level));
    let x = Mat::from_fn(N, 6, |i, j| match j {
        0 => WT[i],
        1 => dummy(CYL[i], 6.0),
        2 => dummy(CYL[i], 8.0),
        3 => HP[i],
        4 => dummy(GEAR[i], 4.0),
        _ => dummy(GEAR[i], 5.0),
    });
    let sizes = [1, 2, 1, 2];
    let gvif = generalized_vif(&x, &sizes);
    for k in 0..4 {
        close(gvif[k], GVIF[k], "GVIF");
        let adj = gvif[k].powf(1.0 / (2.0 * sizes[k] as f64));
        close(adj, GVIF_ADJ[k], "GVIF^(1/(2 df))");
    }
}

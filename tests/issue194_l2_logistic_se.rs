#[test]
fn l2_penalised_coefficients_and_ses_match_rms() {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let y = Col::from_fn(N, |i| Y[i]);
    for (lambda, coef, se) in [(0.5, L05_COEF, L05_SE), (5.0, L5_COEF, L5_SE)] {
        let fit = BinomialRegressor::logistic()
            .lambda(lambda)
            .compute_inference(true)
            .tolerance(1e-14)
            .build()
            .fit(&x, &y)
            .unwrap();
        let r = fit.result();
        let mut got_coef = vec![r.intercept.unwrap()];
        got_coef.extend(r.coefficients.iter());
        let mut got_se = vec![r.intercept_std_error.unwrap()];
        got_se.extend(r.std_errors.as_ref().unwrap().iter());
        for k in 0..3 {
            assert!(
                (got_coef[k] - coef[k]).abs() < 1e-7 * (1.0 + coef[k].abs()),
                "lambda {lambda} coef {k}: {} vs rms {}",
                got_coef[k],
                coef[k]
            );
            assert!(
                (got_se[k] - se[k]).abs() < 1e-7 * se[k],
                "lambda {lambda} se {k}: {} vs rms {}",
                got_se[k],
                se[k]
            );
        }
    }
}

#[test]
fn logistic_regression_l2_uses_the_same_penalised_ses() {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let y = Col::from_fn(N, |i| Y[i]);
    let fit = LogisticRegression::builder()
        .l2(5.0)
        .compute_inference(true)
        .tolerance(1e-14)
        .build()
        .fit(&x, &y)
        .unwrap();
    let se = fit.inner().result().std_errors.as_ref().unwrap();
    for k in 0..2 {
        assert!(
            (se[k] - L5_SE[k + 1]).abs() < 1e-7 * L5_SE[k + 1],
            "se {k}: {} vs rms {}",
            se[k],
            L5_SE[k + 1]
        );
    }
}

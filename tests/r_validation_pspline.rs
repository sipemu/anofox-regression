fn fit(model: PSplineRegressor) -> FittedPSpline {
    let x = Mat::from_fn(X.len(), 1, |i, _| X[i]);
    let y = Col::from_fn(Y.len(), |i| Y[i]);
    model.fit(&x, &y).unwrap()
}

fn close(got: &[f64], want: &[f64], tol: f64, what: &str) {
    assert_eq!(got.len(), want.len(), "{what}: length");
    for (k, (g, w)) in got.iter().zip(want).enumerate() {
        assert!(
            (g - w).abs() <= tol * (1.0 + w.abs()),
            "{what}[{k}]: {g} vs mgcv {w}"
        );
    }
}

fn check(
    f: &FittedPSpline,
    stats: &[f64; 4],
    fitted: &[f64],
    pred: &[f64; 16],
    tol: f64,
    what: &str,
) {
    let r = f.result();
    let n = X.len() as f64;
    let rss: f64 = r.residuals.iter().map(|e| e * e).sum();
    let gcv = n * rss / (n - f.edf()).powi(2);
    close(
        &[f.edf(), f.sigma2(), gcv],
        &stats[..3],
        tol,
        &format!("{what} edf / sig2 / gcv"),
    );
    close(
        &[f.lambda()],
        &stats[3..],
        1e3 * tol,
        &format!("{what} lambda"),
    );
    let fv: Vec<f64> = r.fitted_values.iter().copied().collect();
    close(&fv, fitted, tol, &format!("{what} fitted"));
    let xn = Mat::from_fn(X_NEW.len(), 1, |i, _| X_NEW[i]);
    let p = f.predict_with_interval(&xn, Some(IntervalType::Confidence), 0.95);
    let got: Vec<f64> = p.fit.iter().chain(p.se.iter()).copied().collect();
    close(&got, pred, tol, &format!("{what} predict / se"));
    assert!((r.rmse * r.rmse - r.mse).abs() < 1e-12 * r.mse);
}

#[test]
fn gcv_fit_matches_mgcv() {
    let f = fit(PSplineRegressor::new().with_n_basis(12));
    check(
        &f,
        &GCV_K12_STATS,
        &GCV_K12_FITTED,
        &GCV_K12_PRED,
        1e-6,
        "k = 12",
    );
    let f = fit(PSplineRegressor::new()
        .with_n_basis(20)
        .with_penalty_order(3));
    check(
        &f,
        &GCV_K20_M3_STATS,
        &GCV_K20_M3_FITTED,
        &GCV_K20_M3_PRED,
        1e-6,
        "k = 20, m = 3",
    );
}

#[test]
fn fixed_lambda_matches_mgcv_sp() {
    let f = fit(PSplineRegressor::new().with_n_basis(12).with_lambda(2.0));
    check(
        &f,
        &FIXED_K12_STATS,
        &FIXED_K12_FITTED,
        &FIXED_K12_PRED,
        1e-10,
        "fixed lambda",
    );
}

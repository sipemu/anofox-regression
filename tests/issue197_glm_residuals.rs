const N: usize = 20;

fn x() -> Mat<f64> {
    Mat::from_fn(N, 1, |i, _| X[i])
}

fn y(v: &[f64; N]) -> Col<f64> {
    Col::from_fn(N, |i| v[i])
}

fn check(got: [Col<f64>; 3], want: [&[f64; N]; 3], what: &str) {
    for (t, name) in ["pearson", "deviance", "working"].iter().enumerate() {
        for i in 0..N {
            let (a, b) = (got[t][i], want[t][i]);
            assert!(
                (a - b).abs() < 1e-7 * (1.0 + b.abs()),
                "{what} {name}[{i}]: {a} vs R {b}"
            );
        }
    }
}

#[test]
fn weighted_binomial_residuals_match_r() {
    let fit = BinomialRegressor::logistic()
        .weights(y(&M))
        .tolerance(1e-12)
        .build()
        .fit(&x(), &Col::from_fn(N, |i| S[i] / M[i]))
        .unwrap();
    check(
        [
            fit.pearson_residuals(),
            fit.deviance_residuals(),
            fit.working_residuals(),
        ],
        [&BINW_PEARSON, &BINW_DEVIANCE, &BINW_WORKING],
        "binomial",
    );
    let dev: f64 = fit.deviance_residuals().iter().map(|r| r * r).sum();
    assert!((dev - fit.deviance).abs() < 1e-9 * fit.deviance);
}

#[test]
fn count_and_positive_family_residuals_match_r() {
    let f = PoissonRegressor::log()
        .tolerance(1e-12)
        .build()
        .fit(&x(), &y(&YC))
        .unwrap();
    check(
        [
            f.pearson_residuals(),
            f.deviance_residuals(),
            f.working_residuals(),
        ],
        [&POIS_PEARSON, &POIS_DEVIANCE, &POIS_WORKING],
        "poisson",
    );
    let f = NegativeBinomialRegressor::with_theta(3.0)
        .tolerance(1e-12)
        .build()
        .fit(&x(), &y(&YC))
        .unwrap();
    check(
        [
            f.pearson_residuals(),
            f.deviance_residuals(),
            f.working_residuals(),
        ],
        [&NB_PEARSON, &NB_DEVIANCE, &NB_WORKING],
        "negative binomial",
    );
    let f = TweedieRegressor::gamma()
        .tolerance(1e-12)
        .build()
        .fit(&x(), &y(&YG))
        .unwrap();
    check(
        [
            f.pearson_residuals(),
            f.deviance_residuals(),
            f.working_residuals(),
        ],
        [&GAMMA_PEARSON, &GAMMA_DEVIANCE, &GAMMA_WORKING],
        "gamma",
    );
    let f = TweedieRegressor::builder()
        .var_power(1.5)
        .link_power(0.0)
        .tolerance(1e-12)
        .build()
        .fit(&x(), &y(&YG))
        .unwrap();
    check(
        [
            f.pearson_residuals(),
            f.deviance_residuals(),
            f.working_residuals(),
        ],
        [&TW_PEARSON, &TW_DEVIANCE, &TW_WORKING],
        "tweedie",
    );
}

fn close(a: f64, b: f64, tol: f64, what: &str) {
    assert!(
        (a - b).abs() <= tol * (1.0 + b.abs()),
        "{what}: {a} vs R {b}"
    );
}

#[test]
fn gamma_and_tweedie_link_powers_match_r() {
    let x = Mat::from_fn(N, 1, |i, _| X[i]);
    let y = Col::from_fn(N, |i| YG[i]);
    // (var_power, link_power, reference)
    let cases = [
        (2.0, -1.0, GAMMA_INVERSE, "Gamma(inverse)"),
        (2.0, 1.0, GAMMA_IDENTITY, "Gamma(identity)"),
        (1.5, 1.0, TW15_IDENTITY, "tweedie(1.5, identity)"),
        (1.5, 0.5, TW15_SQRT, "tweedie(1.5, sqrt)"),
        (1.5, -1.0, TW15_INVERSE, "tweedie(1.5, inverse)"),
    ];
    for (p, q, want, what) in cases {
        let f = TweedieRegressor::builder()
            .var_power(p)
            .link_power(q)
            .tolerance(1e-13)
            .build()
            .fit(&x, &y)
            .unwrap();
        close(
            f.result().intercept.unwrap(),
            want[0],
            1e-7,
            &format!("{what} intercept"),
        );
        close(
            f.result().coefficients[0],
            want[1],
            1e-7,
            &format!("{what} slope"),
        );
        close(f.deviance, want[2], 1e-8, &format!("{what} deviance"));
    }
}

#[test]
fn rls_with_forgetting_factor_is_exponentially_weighted_least_squares() {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X[i] } else { X2[i] });
    let y = Col::from_fn(N, |i| YR[i]);
    for (lambda, want) in [(0.95, RLS_095), (0.99, RLS_099)] {
        let f = RlsRegressor::builder()
            .forgetting_factor(lambda)
            .build()
            .fit(&x, &y)
            .unwrap();
        let r = f.result();
        let got = [r.intercept.unwrap(), r.coefficients[0], r.coefficients[1]];
        for k in 0..3 {
            close(got[k], want[k], 1e-8, &format!("lambda {lambda} coef {k}"));
        }
    }
}

#[test]
fn weighted_isotonic_matches_pava() {
    let x = Mat::from_fn(N, 1, |i, _| X[i]);
    let y = Col::from_fn(N, |i| YI[i]);
    let f = IsotonicRegressor::builder()
        .weights(Col::from_fn(N, |i| WI[i]))
        .build()
        .fit(&x, &y)
        .unwrap();
    for (i, &want) in ISO_W.iter().enumerate().take(N) {
        close(
            f.result().fitted_values[i],
            want,
            1e-10,
            &format!("fitted[{i}]"),
        );
    }
}

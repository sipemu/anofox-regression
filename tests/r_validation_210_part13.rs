const N: usize = 80;

fn x() -> Mat<f64> {
    Mat::from_fn(N, 3, |i, j| X_FLAT[i * 3 + j])
}

fn fit(
    family: PenalizedGlmFamily,
    y: &[f64],
    priors: Vec<PriorSpec>,
    inference: bool,
) -> FittedPenalizedGlm {
    PenalizedGlmRegressor::builder()
        .family(family)
        .priors(priors)
        .compute_inference(inference)
        .tolerance(1e-13)
        .build()
        .fit(&x(), &Col::from_fn(N, |i| y[i]))
        .unwrap()
}

fn coefs(f: &FittedPenalizedGlm) -> Vec<f64> {
    [
        vec![f.intercept().unwrap()],
        f.coefficients().iter().copied().collect(),
    ]
    .concat()
}

fn close(got: &[f64], want: &[f64], tol: f64, what: &str) {
    for (k, (g, w)) in got.iter().zip(want).enumerate() {
        assert!(
            (g - w).abs() <= tol * (1.0 + w.abs()),
            "{what}[{k}]: {g} vs R {w}"
        );
    }
}

fn laplace(loc: [f64; 3]) -> Vec<PriorSpec> {
    let mut p = vec![PriorSpec::flat()];
    p.extend((0..3).map(|j| PriorSpec::laplace(loc[j], SCALES[j])));
    p
}

#[test]
fn laplace_priors_match_glmnet_lasso() {
    let f = fit(
        PenalizedGlmFamily::poisson(),
        &Y_POIS,
        laplace([0.0; 3]),
        false,
    );
    close(&coefs(&f), &LAPLACE_POIS, 1e-8, "poisson");
    let f = fit(
        PenalizedGlmFamily::binomial(),
        &Y_BIN,
        laplace([0.0; 3]),
        false,
    );
    close(&coefs(&f), &LAPLACE_BIN, 1e-8, "binomial");
    // the third slope is shrunk to exactly zero, as in glmnet
    assert_eq!(f.coefficients()[2], 0.0);
    let f = fit(PenalizedGlmFamily::poisson(), &Y_POIS, laplace(LOC), false);
    close(
        &coefs(&f),
        &LAPLACE_POIS_LOC,
        1e-8,
        "poisson, located prior",
    );
    // the first slope sits exactly at its prior location
    assert_eq!(f.coefficients()[0], LOC[0]);
}

#[test]
fn tweedie_between_poisson_and_gamma_matches_statmod() {
    let f = fit(PenalizedGlmFamily::tweedie(1.5), &Y_TWEEDIE, vec![], true);
    close(&coefs(&f), &TWEEDIE_COEF, 1e-7, "tweedie p = 1.5 coef");
    let v = f.vcov().unwrap();
    let se: Vec<f64> = (0..4).map(|j| v[(j, j)].sqrt()).collect();
    close(&se, &TWEEDIE_SE, 1e-6, "tweedie p = 1.5 se");
}

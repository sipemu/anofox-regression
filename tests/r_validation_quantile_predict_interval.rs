fn check(tau: f64, se: QuantileSe, level: f64, want: &[f64; 9], what: &str) {
    check_fit(tau, true, se, level, want, what);
}

fn check_fit(tau: f64, intercept: bool, se: QuantileSe, level: f64, want: &[f64; 9], what: &str) {
    let x = Mat::from_fn(60, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    let y = Col::from_fn(60, |i| Y[i]);
    let inf = quantile_inference(&x, &y, tau, intercept, se, 0.95).unwrap();
    let df = inf.df_residual;
    let new = Mat::from_fn(3, 2, |i, j| if j == 0 { NEW_X1[i] } else { NEW_X2[i] });
    let p = inf.predict_interval(&new, level).unwrap();
    for i in 0..3 {
        let got = [p.fit[i], p.lower[i], p.upper[i]];
        for (k, name) in ["fit", "lower", "upper"].iter().enumerate() {
            let w = want[3 * k + i];
            assert!(
                (got[k] - w).abs() <= 1e-8 * (1.0 + w.abs()),
                "{what} {name}[{i}]: {} vs R {w}",
                got[k]
            );
        }
        assert!((p.se[i] - (p.upper[i] - p.fit[i]) / quantile_t(level, df)).abs() < 1e-12);
    }
}

fn quantile_t(level: f64, df: f64) -> f64 {
    use statrs::distribution::{ContinuousCDF, StudentsT};
    StudentsT::new(0.0, 1.0, df)
        .unwrap()
        .inverse_cdf(1.0 - (1.0 - level) / 2.0)
}

#[test]
fn iid_intervals_match_predict_rq() {
    check(
        0.5,
        QuantileSe::Iid,
        0.95,
        &IID_TAU50_L95,
        "iid tau 0.5 95%",
    );
    check(0.5, QuantileSe::Iid, 0.8, &IID_TAU50_L80, "iid tau 0.5 80%");
    check(
        0.25,
        QuantileSe::Iid,
        0.95,
        &IID_TAU25_L95,
        "iid tau 0.25 95%",
    );
    check(
        0.25,
        QuantileSe::Iid,
        0.8,
        &IID_TAU25_L80,
        "iid tau 0.25 80%",
    );
}


fn data() -> (Mat<f64>, Col<f64>) {
    let x = Mat::from_fn(N, 2, |i, j| if j == 0 { X1[i] } else { X2[i] });
    (x, Col::from_fn(N, |i| Y[i]))
}

/// Relative comparison: the p-values are ~1e-30 … 1e-80, so an absolute
/// tolerance would accept 0.
fn close_rel(a: f64, b: f64, what: &str) {
    assert!(a > 0.0, "{what}: underflowed to {a}");
    assert!((a / b - 1.0).abs() < 1e-6, "{what}: {a:e} vs R {b:e}");
}

#[test]
fn ols_and_wls_tiny_p_values_match_r() {
    let (x, y) = data();
    let fit = OlsRegressor::builder()
        .compute_inference(true)
        .build()
        .fit(&x, &y)
        .unwrap();
    let r = fit.result();
    close_rel(r.intercept_p_value.unwrap(), OLS_P[0], "OLS p0");
    for j in 0..2 {
        close_rel(r.p_values.as_ref().unwrap()[j], OLS_P[j + 1], "OLS p");
    }
    close_rel(r.f_pvalue, OLS_F_P, "OLS F p-value");

    let fit = WlsRegressor::builder()
        .weights(Col::from_fn(N, |i| W[i]))
        .compute_inference(true)
        .build()
        .fit(&x, &y)
        .unwrap();
    let r = fit.result();
    close_rel(r.intercept_p_value.unwrap(), WLS_P[0], "WLS p0");
    for j in 0..2 {
        close_rel(r.p_values.as_ref().unwrap()[j], WLS_P[j + 1], "WLS p");
    }
}

#[test]
fn gls_tiny_p_values_match_nlme() {
    let (x, y) = data();
    let group = vec![0usize; N];
    let fit = GlsRegressor::builder()
        .build()
        .fit(&x, &y, &group, None)
        .unwrap();
    let p = fit.p_values();
    for k in 0..3 {
        close_rel(p[k], GLS_P[k], "GLS p");
    }
}

#[test]
fn hc1_tiny_p_values_match_sandwich() {
    let (x, y) = data();
    let fit = OlsRegressor::builder().build().fit(&x, &y).unwrap();
    let r = fit.result();
    let hc = compute_hc_inference(
        &x,
        &r.coefficients,
        r.intercept,
        &r.residuals,
        &r.aliased,
        true,
        HcType::HC1,
        0.95,
    )
    .unwrap();
    close_rel(hc.intercept.unwrap().p_value, HC1_P[0], "HC1 p0");
    for j in 0..2 {
        close_rel(hc.p_values[j], HC1_P[j + 1], "HC1 p");
    }
}

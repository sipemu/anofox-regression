const N: usize = 80;

#[test]
fn information_criteria_match_greybox() {
    let x = Mat::from_fn(N, 1, |i, _| X[i]);
    let cases = [
        (AlmDistribution::Normal, &YN, NORMAL, "normal"),
        (AlmDistribution::Poisson, &YP, POISSON, "poisson"),
        (AlmDistribution::Geometric, &YP, GEOMETRIC, "geometric"),
        (
            AlmDistribution::Exponential,
            &YE,
            EXPONENTIAL,
            "exponential",
        ),
        (AlmDistribution::Binomial, &YB, BINOMIAL, "binomial"),
    ];
    for (dist, y, want, what) in cases {
        let y = Col::from_fn(N, |i| y[i]);
        let fit = AlmRegressor::builder()
            .distribution(dist)
            .build()
            .fit(&x, &y)
            .unwrap();
        let r = fit.result();
        assert_eq!(r.n_parameters, want[0] as usize, "{what}: nparam");
        let got = [r.log_likelihood, r.aic, r.aicc, r.bic];
        for (k, name) in ["logLik", "AIC", "AICc", "BIC"].iter().enumerate() {
            assert!(
                (got[k] - want[k + 1]).abs() < 1e-4,
                "{what} {name}: {} vs greybox {}",
                got[k],
                want[k + 1]
            );
        }
    }
}
